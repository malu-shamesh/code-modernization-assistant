C     RANPM - PARK-MILLER MINIMAL STANDARD GENERATOR (SCHRAGE METHOD)
C
C     X(N+1) = MOD(16807*X(N), 2**31-1) WITHOUT OVERFLOWING A 32-BIT
C     INTEGER: WITH Q = M/A AND R = MOD(M,A) ONE HAS
C     A*X MOD M = A*(X - Q*K) - R*K FOR K = X/Q, PLUS M WHEN NEGATIVE.
C     THE STATE LIVES IN COMMON /RNGST/; BLOCK DATA STARTS IT AT 1.
C
      BLOCK DATA RNGBD
      INTEGER IX, NDRAW
      COMMON /RNGST/ IX, NDRAW
      DATA IX /1/, NDRAW /0/
      END
C
C     RESTART THE SEQUENCE.  THE SIGN OF ISEED IS IGNORED AND A SEED
C     THAT REDUCES TO 0 IS REPLACED BY 1 (0 IS A FIXED POINT).
      SUBROUTINE RSEED(ISEED)
      INTEGER ISEED, IX, NDRAW, IM
      PARAMETER (IM = 2147483647)
      COMMON /RNGST/ IX, NDRAW
      IX = MOD(ABS(ISEED), IM)
      IF (IX .EQ. 0) IX = 1
      NDRAW = 0
      RETURN
      END
C
C     NEXT TERM OF THE SEQUENCE, 1 .. 2**31-2
      INTEGER FUNCTION RNEXT()
      INTEGER IX, NDRAW, IA, IM, IQ, IR, K
      PARAMETER (IA = 16807, IM = 2147483647, IQ = 127773, IR = 2836)
      COMMON /RNGST/ IX, NDRAW
      K = IX / IQ
      IX = IA * (IX - K * IQ) - IR * K
      IF (IX .LT. 0) IX = IX + IM
      NDRAW = NDRAW + 1
      RNEXT = IX
      RETURN
      END
C
C     RANDOM INTEGER IN 1..N; N .LT. 1 GIVES 0 AND USES NO DRAW
      INTEGER FUNCTION RBOUND(N)
      INTEGER N, RNEXT
      IF (N .LT. 1) THEN
         RBOUND = 0
      ELSE
         RBOUND = 1 + MOD(RNEXT(), N)
      END IF
      RETURN
      END
C
C     NUMBER OF TERMS DRAWN SINCE THE LAST RSEED
      SUBROUTINE RSTAT(NDR)
      INTEGER NDR, IX, NDRAW
      COMMON /RNGST/ IX, NDRAW
      NDR = NDRAW
      RETURN
      END
C
C     RANDOM PERMUTATION OF 1..N (FISHER-YATES, FROM THE TOP DOWN)
      SUBROUTINE RSHUF(N, IPERM)
      INTEGER N, IPERM(*), RBOUND, ITMP, J
      DO 10 I = 1, N
         IPERM(I) = I
   10 CONTINUE
      DO 20 I = N, 2, -1
         J = RBOUND(I)
         ITMP = IPERM(I)
         IPERM(I) = IPERM(J)
         IPERM(J) = ITMP
   20 CONTINUE
      RETURN
      END
C
C     SELECTION SAMPLING (KNUTH ALGORITHM S): M OF THE INTEGERS 1..N
C     IN INCREASING ORDER.  RECORD IT+1 IS TAKEN WITH PROBABILITY
C     (M-NSEL)/(N-IT).  NSEL IS THE NUMBER OF VALUES STORED IN ISAMP
C     (0 WHEN M IS NOT IN 1..N).  THE SCAN STOPS AS SOON AS M ARE IN.
      SUBROUTINE RSAMP(N, M, ISAMP, NSEL)
      INTEGER N, M, ISAMP(*), NSEL, RBOUND
      NSEL = 0
      IF (M .LT. 1 .OR. M .GT. N) RETURN
      DO 10 IT = 0, N - 1
         IF (RBOUND(N - IT) .GT. M - NSEL) GO TO 10
         NSEL = NSEL + 1
         ISAMP(NSEL) = IT + 1
         IF (NSEL .EQ. M) RETURN
   10 CONTINUE
      RETURN
      END
