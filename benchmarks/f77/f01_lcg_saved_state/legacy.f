C     LCGSAV - SMALL LINEAR CONGRUENTIAL RANDOM NUMBER GENERATOR
C
C     X(N+1) = MOD(75*X(N) + 74, 65537)       (THE ZX81 RULE)
C
C     THE GENERATOR STATE IS A SAVED LOCAL OF LCGINT, SO THE ROUTINES
C     BELOW SHARE IT ONLY BY CALLING LCGINT WITH THE PROPER MODE.
C     CALL LCGINT(0, ISEED) FIRST TO START A REPRODUCIBLE SEQUENCE.
C
      INTEGER FUNCTION LCGINT(MODE, ISEED)
C     MODE = 0   RESTART THE SEQUENCE FROM ISEED, RETURN THE STATE
C     MODE = 1   ADVANCE THE SEQUENCE, RETURN THE NEW STATE
C     MODE = 2   RETURN THE NUMBER OF TERMS DRAWN SINCE THE RESTART
C     ANY OTHER MODE RETURNS -1
      INTEGER MODE, ISEED
      INTEGER IX, NCALL, IA, IC, IM
      PARAMETER (IA = 75, IC = 74, IM = 65537)
      SAVE IX, NCALL
      DATA IX /1/, NCALL /0/
      IF (MODE .EQ. 0) THEN
         IX = MOD(ABS(ISEED), IM)
         NCALL = 0
         LCGINT = IX
      ELSE IF (MODE .EQ. 1) THEN
         IX = MOD(IA*IX + IC, IM)
         NCALL = NCALL + 1
         LCGINT = IX
      ELSE IF (MODE .EQ. 2) THEN
         LCGINT = NCALL
      ELSE
         LCGINT = -1
      END IF
      RETURN
      END
C
C     UNIFORM DEVIATE IN THE HALF-OPEN INTERVAL [0,1)
      REAL FUNCTION LCGUNI()
      INTEGER LCGINT
      LCGUNI = FLOAT(LCGINT(1, 0)) / 65537.0
      RETURN
      END
C
C     INTEGER DEVIATE IN 1..N (N MUST NOT EXCEED 32767)
      INTEGER FUNCTION LCGRNG(N)
      INTEGER LCGINT
      LCGRNG = 1 + (LCGINT(1, 0) * N) / 65537
      RETURN
      END
C
C     FILL X(1..N) WITH UNIFORM DEVIATES
      SUBROUTINE LCGFIL(N, X)
      REAL X(*)
      REAL LCGUNI
      DO 10 I = 1, N
         X(I) = LCGUNI()
   10 CONTINUE
      RETURN
      END
