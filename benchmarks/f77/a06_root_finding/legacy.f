C     ROOT FINDING FOR A FUNCTION OF ONE VARIABLE: NEWTON-RAPHSON AND
C     BISECTION.  F (AND DF, THE DERIVATIVE) ARE USER FUNCTIONS OF ONE
C     DOUBLE PRECISION ARGUMENT, SUPPLIED AS EXTERNAL PROCEDURES.
C
C     NEWTON - ON ENTRY X IS THE STARTING GUESS, ON EXIT THE LAST
C     ITERATE.  A STEP IS ACCEPTED WHEN |DX| <= TOL*MAX(1,|X|).
C        IERR = 0  CONVERGED
C        IERR = 1  NOT CONVERGED IN MAXIT STEPS
C        IERR = 2  DERIVATIVE TOO SMALL TO CONTINUE
C     NIT IS THE NUMBER OF STEPS TAKEN.
      SUBROUTINE NEWTON(F, DF, X, TOL, MAXIT, NIT, IERR)
      EXTERNAL F, DF
      DOUBLE PRECISION F, DF, X, TOL, FX, DFX, DX
      INTEGER MAXIT, NIT, IERR
      IERR = 1
      DO 10 NIT = 1, MAXIT
         FX = F(X)
         DFX = DF(X)
         IF (DABS(DFX) .LT. 1.0D-14) THEN
            IERR = 2
            GO TO 20
         END IF
         DX = FX/DFX
         X = X - DX
         IF (DABS(DX) .LE. TOL*DMAX1(1.0D0, DABS(X))) THEN
            IERR = 0
            GO TO 20
         END IF
   10 CONTINUE
C     THE LOOP RAN TO COMPLETION, LEAVING NIT = MAXIT+1: REPORT MAXIT
      NIT = MAXIT
   20 RETURN
      END
C
C     BISECT - ROOT OF F IN [A,B] BY INTERVAL HALVING.  F(A) AND F(B)
C     MUST DIFFER IN SIGN, OTHERWISE THE ALTERNATE RETURN IS TAKEN
C     (WITH NIT = 0).  ITERATION STOPS WHEN F(MID) IS EXACTLY ZERO OR
C     THE HALF-WIDTH OF THE INTERVAL IS BELOW TOL.  ROOT IS THE LAST
C     MIDPOINT AND NIT THE NUMBER OF HALVINGS DONE (MAXIT AT MOST).
      SUBROUTINE BISECT(F, A, B, TOL, MAXIT, ROOT, NIT, *)
      EXTERNAL F
      DOUBLE PRECISION F, A, B, TOL, ROOT
      DOUBLE PRECISION LO, HI, MID, FLO, FHI, FMID
      INTEGER MAXIT, NIT
      LO = A
      HI = B
      FLO = F(LO)
      FHI = F(HI)
      NIT = 0
      IF (FLO*FHI .GT. 0.0D0) RETURN 1
      MID = LO
      DO 30 NIT = 1, MAXIT
         MID = 0.5D0*(LO + HI)
         FMID = F(MID)
         IF (FMID .EQ. 0.0D0) GO TO 40
         IF (0.5D0*(HI - LO) .LT. TOL) GO TO 40
         IF (SIGN(1.0D0, FMID) .EQ. SIGN(1.0D0, FLO)) THEN
            LO = MID
            FLO = FMID
         ELSE
            HI = MID
         END IF
   30 CONTINUE
      NIT = MAXIT
   40 ROOT = MID
      RETURN
      END
