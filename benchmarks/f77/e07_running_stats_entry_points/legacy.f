C     RSTAT - RUNNING STATISTICS PACKAGE WITH SEVERAL ENTRY POINTS
C
C     ALL ENTRIES BELONG TO ONE PROGRAM UNIT AND SHARE ITS SAVED
C     LOCAL VARIABLES, SO THE ACCUMULATORS PERSIST BETWEEN CALLS.
C
C        CALL RSTRST                      CLEAR THE ACCUMULATORS
C        CALL RSTADD(X)                   ADD ONE OBSERVATION
C        CALL RSTGET(CNT,XMEAN,XVAR,*n)   COUNT, MEAN, SAMPLE VARIANCE
C        CALL RSTRNG(XMIN,XMAX,*n)        SMALLEST AND LARGEST VALUE
C        CALL RSTALL(N,X)                 RESET, THEN ADD X(1) ... X(N)
C
C     THE ALTERNATE RETURN IS TAKEN WHEN NO OBSERVATION HAS BEEN
C     ADDED YET.  THE OUTPUT ARGUMENTS ARE SET BEFORE IT IS TAKEN.
C     THE MEAN AND VARIANCE USE WELFORD'S UPDATE, WHICH DOES NOT
C     LOSE ACCURACY TO CANCELLATION.
C
      SUBROUTINE RSTRST
      INTEGER N, CNT
      DOUBLE PRECISION X, XMEAN, XVAR, XMIN, XMAX
      DOUBLE PRECISION WMEAN, WM2, XLO, XHI, DELTA
      SAVE N, WMEAN, WM2, XLO, XHI
      DATA N /0/, WMEAN /0.0D0/, WM2 /0.0D0/
      DATA XLO /0.0D0/, XHI /0.0D0/
      N = 0
      WMEAN = 0.0D0
      WM2 = 0.0D0
      XLO = 0.0D0
      XHI = 0.0D0
      RETURN
C
      ENTRY RSTADD(X)
      N = N + 1
      DELTA = X - WMEAN
      WMEAN = WMEAN + DELTA / N
      WM2 = WM2 + DELTA * (X - WMEAN)
      IF (N .GT. 1) GO TO 10
      XLO = X
      XHI = X
      RETURN
   10 IF (X .LT. XLO) XLO = X
      IF (X .GT. XHI) XHI = X
      RETURN
C
      ENTRY RSTGET(CNT, XMEAN, XVAR, *)
      CNT = N
      XMEAN = WMEAN
      XVAR = 0.0D0
      IF (N .EQ. 0) RETURN 1
      IF (N .GT. 1) XVAR = WM2 / (N - 1)
      RETURN
C
      ENTRY RSTRNG(XMIN, XMAX, *)
      XMIN = XLO
      XMAX = XHI
      IF (N .EQ. 0) RETURN 1
      RETURN
      END
C
      SUBROUTINE RSTALL(N, X)
      INTEGER N, I
      DOUBLE PRECISION X(N)
      CALL RSTRST
      DO 10 I = 1, N
         CALL RSTADD(X(I))
   10 CONTINUE
      RETURN
      END
