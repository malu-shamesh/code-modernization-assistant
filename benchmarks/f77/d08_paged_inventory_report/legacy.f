C     PGRPT - PAGINATED PARTS INVENTORY REPORT
C
C     PAGE CONTROL LIVES IN COMMON /PGCTL/, SHARED BY ALL ROUTINES
C        LPP    LINES PER PAGE, HEADING LINES INCLUDED
C        NLINE  LINES ALREADY WRITTEN ON THE CURRENT PAGE
C        NPAGE  NUMBER OF THE CURRENT PAGE
C     A NEW PAGE, WITH ITS HEADING, STARTS WHEN NLINE REACHES LPP.
C     ALL OUTPUT USES EXPLICIT FORMATS.  THE FIRST CHARACTER OF EVERY
C     LINE IS A BLANK, A RELIC OF THE OLD CARRIAGE CONTROL.
C
C     PGINIT  START A NEW REPORT WITH THE GIVEN NUMBER OF LINES A PAGE
C     PRTLIN  WRITE ONE LINE, STARTING A NEW PAGE WHEN THE PAGE IS FULL
C     PRTROW  FORMAT AND WRITE ONE INVENTORY ROW
C     PRTTOT  WRITE THE TOTAL LINE AND THE MEAN LINE
C     PRTMAT  DUMP THE LEADING NR BY NC BLOCK OF A MATRIX
C
      BLOCK DATA PGDATA
      INTEGER LPP, NLINE, NPAGE
      COMMON /PGCTL/ LPP, NLINE, NPAGE
      DATA LPP /55/, NLINE /55/, NPAGE /0/
      END
C
      INTEGER FUNCTION LASTNB(S)
      CHARACTER*(*) S
      INTEGER I
      DO 10 I = LEN(S), 1, -1
         IF (S(I:I) .NE. ' ') THEN
            LASTNB = I
            RETURN
         END IF
   10 CONTINUE
      LASTNB = 0
      RETURN
      END
C
      SUBROUTINE PGINIT(LINES)
      INTEGER LINES
      INTEGER LPP, NLINE, NPAGE
      COMMON /PGCTL/ LPP, NLINE, NPAGE
      LPP = LINES
      NLINE = LINES
      NPAGE = 0
      RETURN
      END
C
      SUBROUTINE PRTLIN(TEXT)
      CHARACTER*(*) TEXT
      INTEGER LPP, NLINE, NPAGE
      COMMON /PGCTL/ LPP, NLINE, NPAGE
      INTEGER LASTNB, N
      IF (NLINE .GE. LPP) THEN
         NPAGE = NPAGE + 1
         WRITE(6, 100) NPAGE
         WRITE(6, 110) 'ITEM        ', 'QTY', 'PRICE', 'VALUE'
         WRITE(6, 120)
         NLINE = 3
      END IF
      N = MAX(LASTNB(TEXT), 1)
      WRITE(6, 130) TEXT(1:N)
      NLINE = NLINE + 1
      RETURN
  100 FORMAT(1X, 15HPARTS INVENTORY, 20X, 5HPAGE , I3)
  110 FORMAT(1X, A12, 2X, A5, 2X, A9, 2X, A11)
  120 FORMAT(1X, 43('-'))
  130 FORMAT(1X, A)
      END
C
      SUBROUTINE PRTROW(NAME, IQTY, PRICE)
      CHARACTER*12 NAME
      INTEGER IQTY
      REAL PRICE
      CHARACTER*60 LINE
      REAL EXT
      EXT = IQTY * PRICE
      WRITE(LINE, 100) NAME, IQTY, PRICE, EXT
      CALL PRTLIN(LINE)
      RETURN
  100 FORMAT(A12, 2X, I5, 2X, F9.2, 2X, F11.2)
      END
C
C     NITEM ITEMS WERE LISTED; THE MEAN VALUE IS GIVEN IN E FORMAT
      SUBROUTINE PRTTOT(IQTOT, TOTVAL, NITEM)
      INTEGER IQTOT, NITEM
      REAL TOTVAL
      CHARACTER*12 LAB
      CHARACTER*60 LINE
      REAL AVG
      LAB = 'TOTAL'
      WRITE(LINE, 100) LAB, IQTOT, TOTVAL
      CALL PRTLIN(LINE)
      IF (NITEM .GT. 0) THEN
         AVG = TOTVAL / NITEM
         WRITE(LINE, 110) NITEM, AVG
         CALL PRTLIN(LINE)
      END IF
      RETURN
  100 FORMAT(A12, 2X, I5, 13X, F11.2)
  110 FORMAT('MEAN OVER', I3, ' ITEMS', 3X, E12.4)
      END
C
C     A IS DIMENSIONED A(LDA,*), SO ONLY THE LEADING BLOCK IS PRINTED.
C     SIX VALUES FIT ON A LINE; THE FORMAT REVERTS TO ITS LAST GROUP,
C     SO CONTINUATION LINES CARRY NO ROW LABEL.
      SUBROUTINE PRTMAT(A, LDA, NR, NC)
      INTEGER LDA, NR, NC
      REAL A(LDA, *)
      INTEGER I, J
      DO 10 I = 1, NR
         WRITE(6, 100) I, (A(I, J), J = 1, NC)
   10 CONTINUE
      RETURN
  100 FORMAT(1X, 'ROW', I3, ':', (6F9.2))
      END
C
      PROGRAM PGRPT
      CHARACTER*12 NAME(6)
      INTEGER IQTY(6), IQTOT, I
      REAL PRICE(6), TOTVAL
      DATA NAME /'BOLT M8', 'WASHER 8', 'NUT M8', 'SPRING',
     &           'GASKET', 'PLATE 200'/
      DATA IQTY /120, 400, 150, 36, 12, 5/
      DATA PRICE /0.35, 0.05, 0.12, 2.50, 18.75, 129.99/
      CALL PGINIT(8)
      IQTOT = 0
      TOTVAL = 0.0
      DO 10 I = 1, 6
         CALL PRTROW(NAME(I), IQTY(I), PRICE(I))
         IQTOT = IQTOT + IQTY(I)
         TOTVAL = TOTVAL + IQTY(I) * PRICE(I)
   10 CONTINUE
C     THE DO VARIABLE I IS 7 AFTER THE LOOP, SO I - 1 ROWS WERE LISTED
      CALL PRTTOT(IQTOT, TOTVAL, I - 1)
      END
