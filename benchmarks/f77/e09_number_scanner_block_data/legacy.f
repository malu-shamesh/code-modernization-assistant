C     TABLE-DRIVEN SCANNER FOR SIGNED DECIMAL NUMBERS
C
C     THE STATE TRANSITION TABLE LIVES IN COMMON BLOCK /FSMTAB/ AND
C     IS FILLED IN BY THE BLOCK DATA UNIT AT THE END OF THIS FILE.
C
C       STATES   1 START           CLASSES  1 SIGN  + -
C                2 AFTER SIGN               2 DIGIT
C                3 INTEGER DIGITS           3 POINT
C                4 POINT, NO DIGIT          4 ANYTHING ELSE
C                5 FRACTION (OR INTEGER FOLLOWED BY A POINT)
C       STATES 3 AND 5 ACCEPT.  STATE 0 MEANS REJECT.
C
C     NUMSCN  VALIDATES A STRING (TRAILING BLANKS ARE IGNORED)
C     NUMVAL  VALUE OF A STRING THAT NUMSCN ACCEPTS
C     NCLASS  CHARACTER CLASS 1 .. 4
C
      SUBROUTINE NUMSCN(STR, OK, IPOS, NDIG)
C
C     OK    TRUE WHEN THE WHOLE STRING IS A NUMBER
C     IPOS  0 WHEN OK; OTHERWISE THE POSITION OF THE REJECTED
C           CHARACTER, OR LENGTH+1 WHEN THE TEXT ENDS TOO EARLY
C     NDIG  NUMBER OF DIGITS SEEN BEFORE THE SCAN STOPPED
C
      CHARACTER*(*) STR
      LOGICAL OK
      INTEGER IPOS, NDIG
      INTEGER ITRANS(5,4), IACC(5)
      COMMON /FSMTAB/ ITRANS, IACC
      INTEGER N, I, ISTATE, ICLS, NCLASS
      NDIG = 0
      IPOS = 0
      N = LEN(STR)
   10 IF (N .EQ. 0) GO TO 20
      IF (STR(N:N) .NE. ' ') GO TO 20
      N = N - 1
      GO TO 10
   20 ISTATE = 1
      I = 0
   30 I = I + 1
      IF (I .GT. N) GO TO 60
      ICLS = NCLASS(STR(I:I))
      ISTATE = ITRANS(ISTATE, ICLS)
      IF (ISTATE .EQ. 0) GO TO 70
      IF (ICLS .EQ. 2) NDIG = NDIG + 1
      GO TO 30
   60 OK = IACC(ISTATE) .EQ. 1
      IF (.NOT. OK) IPOS = N + 1
      RETURN
   70 OK = .FALSE.
      IPOS = I
      RETURN
      END
C
      DOUBLE PRECISION FUNCTION NUMVAL(STR, IERR)
C     IERR IS THE IPOS OF NUMSCN, SO 0 MEANS THE VALUE IS VALID
      CHARACTER*(*) STR
      INTEGER IERR
      LOGICAL OKL
      DOUBLE PRECISION V, SCALE
      INTEGER IPOS, NDIG, I, ID, ISGN, IFRAC
      CALL NUMSCN(STR, OKL, IPOS, NDIG)
      IERR = IPOS
      NUMVAL = 0.0D0
      IF (.NOT. OKL) RETURN
      V = 0.0D0
      SCALE = 1.0D0
      ISGN = 1
      IFRAC = 0
      DO 20 I = 1, LEN(STR)
         IF (STR(I:I) .EQ. ' ') GO TO 30
         IF (STR(I:I) .EQ. '-') ISGN = -1
         IF (STR(I:I) .EQ. '.') IFRAC = 1
         ID = ICHAR(STR(I:I)) - ICHAR('0')
         IF (ID .LT. 0 .OR. ID .GT. 9) GO TO 20
         IF (IFRAC .EQ. 1) GO TO 15
         V = V * 10.0D0 + ID
         GO TO 20
   15    SCALE = SCALE / 10.0D0
         V = V + ID * SCALE
   20 CONTINUE
   30 NUMVAL = ISGN * V
      RETURN
      END
C
      INTEGER FUNCTION NCLASS(C)
      CHARACTER*1 C
      NCLASS = 4
      IF (C .EQ. '+' .OR. C .EQ. '-') NCLASS = 1
      IF (C .GE. '0' .AND. C .LE. '9') NCLASS = 2
      IF (C .EQ. '.') NCLASS = 3
      RETURN
      END
C
      BLOCK DATA FSMDAT
      INTEGER ITRANS(5,4), IACC(5)
      COMMON /FSMTAB/ ITRANS, IACC
C     DATA FILLS ITRANS COLUMN BY COLUMN: ONE COLUMN PER CLASS
      DATA ITRANS /2, 0, 0, 0, 0,
     &             3, 3, 3, 5, 5,
     &             4, 4, 5, 0, 0,
     &             5*0/
      DATA IACC /0, 0, 1, 0, 1/
      END
