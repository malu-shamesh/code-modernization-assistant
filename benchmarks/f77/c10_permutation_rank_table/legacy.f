C**********************************************************************
C     LEXICOGRAPHIC PERMUTATIONS OF 1..N, N .LE. 12
C
C     NXTPRM  NEXT PERMUTATION IN PLACE; AFTER THE LAST ONE IT WRAPS
C             TO THE FIRST AND SETS LAST
C     PRMRNK  ZERO-BASED LEXICOGRAPHIC RANK OF A PERMUTATION
C     PRMUNR  THE PERMUTATION OF A GIVEN RANK
C     PRMSKP  MOVES A PERMUTATION ISTEP RANKS FORWARD (OR BACKWARD),
C             CYCLICALLY
C     NCOUNT  COUNTERS KEPT IN COMMON: 1 = SUCCESSOR STEPS OF NXTPRM,
C             ANYTHING ELSE = VALID PRMRNK CALLS
C
C     12! IS THE LARGEST FACTORIAL THAT FITS IN 32 BITS.  THE TABLE
C     IFACT(0:12) IS COMMON /PRMFAC/ AND THE COUNTERS ARE COMMON
C     /PRMCNT/; BOTH ARE INITIALISED BY THE BLOCK DATA UNIT.
C**********************************************************************
      BLOCK DATA BDPERM
      INTEGER IFACT(0:12), NGEN, NRNK
      COMMON /PRMFAC/ IFACT
      COMMON /PRMCNT/ NGEN, NRNK
      DATA IFACT /1, 1, 2, 6, 24, 120, 720, 5040, 40320, 362880,
     +            3628800, 39916800, 479001600/
      DATA NGEN, NRNK /0, 0/
      END
C
      SUBROUTINE NXTPRM(N, IP, LAST)
      INTEGER N, IP(N)
      LOGICAL LAST
      INTEGER NGEN, NRNK
      COMMON /PRMCNT/ NGEN, NRNK
      INTEGER I, J, L, M, ITMP
C
      LAST = .FALSE.
C     RIGHTMOST ASCENT IP(I) .LT. IP(I+1)
      DO 10 I = N - 1, 1, -1
         IF (IP(I) .LT. IP(I+1)) GO TO 20
   10 CONTINUE
C     NO ASCENT, THE LOOP RAN OUT AND I IS 0: THE REVERSAL AT LABEL 40
C     STARTS AT I+1 = 1 AND TURNS THE WHOLE VECTOR INTO THE FIRST ONE
      LAST = .TRUE.
      GO TO 40
C     SWAP IP(I) WITH THE RIGHTMOST LARGER ELEMENT; J IS USED AFTER
C     THE EARLY EXIT FROM THE LOOP
   20 DO 30 J = N, I + 1, -1
         IF (IP(J) .GT. IP(I)) GO TO 35
   30 CONTINUE
   35 ITMP = IP(I)
      IP(I) = IP(J)
      IP(J) = ITMP
      NGEN = NGEN + 1
C     REVERSE THE SUFFIX IP(I+1..N)
   40 L = I + 1
      M = N
   50 IF (L .GE. M) RETURN
      ITMP = IP(L)
      IP(L) = IP(M)
      IP(M) = ITMP
      L = L + 1
      M = M - 1
      GO TO 50
      END
C
C     PRMRNK - SUM OVER I OF (NUMBER OF SMALLER ELEMENTS TO THE RIGHT
C     OF IP(I)) * (N-I)!.  RESULT -1 FOR N OUTSIDE 0..12.
C
      INTEGER FUNCTION PRMRNK(N, IP)
      INTEGER N, IP(N)
      INTEGER IFACT(0:12), NGEN, NRNK
      COMMON /PRMFAC/ IFACT
      COMMON /PRMCNT/ NGEN, NRNK
      INTEGER I, J, ICNT, IR
C
      PRMRNK = -1
      IF (N .LT. 0 .OR. N .GT. 12) RETURN
      NRNK = NRNK + 1
      IR = 0
      DO 20 I = 1, N - 1
         ICNT = 0
         DO 10 J = I + 1, N
            IF (IP(J) .LT. IP(I)) ICNT = ICNT + 1
   10    CONTINUE
         IR = IR + ICNT * IFACT(N - I)
   20 CONTINUE
      PRMRNK = IR
      RETURN
      END
C
C     PRMUNR - IERR = 1 FOR N OUTSIDE 0..12, 2 FOR K OUTSIDE 0..N!-1
C
      SUBROUTINE PRMUNR(N, K, IP, IERR)
      INTEGER N, K, IP(N), IERR
      INTEGER IFACT(0:12)
      COMMON /PRMFAC/ IFACT
      INTEGER IAV(12), I, J, ID, IREM
C
      IERR = 0
      IF (N .LT. 0 .OR. N .GT. 12) THEN
         IERR = 1
         RETURN
      END IF
      IF (K .LT. 0 .OR. K .GE. IFACT(N)) THEN
         IERR = 2
         RETURN
      END IF
      DO 10 I = 1, N
         IAV(I) = I
   10 CONTINUE
      IREM = K
      DO 40 I = 1, N
         ID = IREM / IFACT(N - I)
         IREM = MOD(IREM, IFACT(N - I))
C        TAKE THE (ID+1)-TH UNUSED VALUE AND CLOSE THE GAP
         IP(I) = IAV(ID + 1)
         DO 30 J = ID + 1, N - I
            IAV(J) = IAV(J+1)
   30    CONTINUE
   40 CONTINUE
      RETURN
      END
C
C     PRMSKP - NEW RANK = (RANK + ISTEP) MOD N!, NEVER NEGATIVE.
C     IERR = 1 FOR N OUTSIDE 0..12, OTHERWISE THE CODE OF PRMUNR.
C
      SUBROUTINE PRMSKP(N, IP, ISTEP, IERR)
      INTEGER N, IP(N), ISTEP, IERR
      INTEGER IFACT(0:12)
      COMMON /PRMFAC/ IFACT
      INTEGER PRMRNK, K, NF
C
      IERR = 1
      IF (N .LT. 0 .OR. N .GT. 12) RETURN
      NF = IFACT(N)
C     MOD TAKES THE SIGN OF ITS FIRST ARGUMENT: LIFT NEGATIVE RESULTS
      K = MOD(PRMRNK(N, IP) + ISTEP, NF)
      IF (K .LT. 0) K = K + NF
      CALL PRMUNR(N, K, IP, IERR)
      RETURN
      END
C
      INTEGER FUNCTION NCOUNT(IWHICH)
      INTEGER IWHICH, NGEN, NRNK
      COMMON /PRMCNT/ NGEN, NRNK
C
      IF (IWHICH .EQ. 1) THEN
         NCOUNT = NGEN
      ELSE
         NCOUNT = NRNK
      END IF
      RETURN
      END
