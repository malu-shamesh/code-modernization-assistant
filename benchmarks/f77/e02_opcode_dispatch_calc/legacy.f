C     ACCUMULATOR CALCULATOR - OPCODE DISPATCH BY COMPUTED GO TO
C
C     CALC    RUNS A LIST OF (OPCODE, OPERAND) PAIRS ON ONE ACCUMULATOR
C     KSIGN   THREE-WAY SIGN CLASSIFICATION WITH A DEAD BAND
C     TALLY   COUNTS NEGATIVE, ZERO AND POSITIVE ELEMENTS OF A VECTOR
C
      SUBROUTINE CALC(NOPS, IOP, ARG, ACC, IERR)
C
C     OPCODES   1  ACC = ACC + ARG(I)       4  ACC = ACC / ARG(I)
C               2  ACC = ACC - ARG(I)       5  ACC = -ACC
C               3  ACC = ACC * ARG(I)       6  ACC = ABS(ACC)
C     THE ACCUMULATOR STARTS AT ZERO.  ON AN ERROR THE ACCUMULATOR
C     KEEPS THE VALUE IT HAD BEFORE THE FAILING INSTRUCTION.
C     IERR   0  ALL NOPS INSTRUCTIONS EXECUTED
C            1  UNKNOWN OPCODE
C            2  DIVISION BY ZERO
C
      INTEGER NOPS, IOP(*), IERR, I
      REAL ARG(*), ACC
      ACC = 0.0
      IERR = 0
      I = 0
   10 I = I + 1
      IF (I .GT. NOPS) RETURN
      GO TO (110, 120, 130, 140, 150, 160), IOP(I)
      IERR = 1
      RETURN
  110 ACC = ACC + ARG(I)
      GO TO 10
  120 ACC = ACC - ARG(I)
      GO TO 10
  130 ACC = ACC * ARG(I)
      GO TO 10
  140 IF (ARG(I)) 145, 190, 145
  145 ACC = ACC / ARG(I)
      GO TO 10
  150 ACC = -ACC
      GO TO 10
  160 ACC = ABS(ACC)
      GO TO 10
  190 IERR = 2
      RETURN
      END
C
      INTEGER FUNCTION KSIGN(X, EPS)
C
C     -1, 0 OR +1 ACCORDING TO X, WHERE |X| .LE. EPS COUNTS AS ZERO.
C
      REAL X, EPS
      IF (ABS(X) - EPS) 10, 10, 20
   10 KSIGN = 0
      RETURN
   20 IF (X) 30, 30, 40
   30 KSIGN = -1
      RETURN
   40 KSIGN = 1
      RETURN
      END
C
      SUBROUTINE TALLY(N, X, EPS, NNEG, NZERO, NPOS)
C
C     CLASSIFY X(1) ... X(N) WITH KSIGN AND COUNT EACH CLASS.  THE
C     CLASS NUMBER IS SHIFTED BY TWO SO THAT IT CAN DRIVE A COMPUTED
C     GO TO DIRECTLY.
C
      INTEGER N, NNEG, NZERO, NPOS, I, K, KSIGN
      REAL X(N), EPS
      NNEG = 0
      NZERO = 0
      NPOS = 0
      DO 50 I = 1, N
         K = KSIGN(X(I), EPS) + 2
         GO TO (10, 20, 30), K
   10    NNEG = NNEG + 1
         GO TO 50
   20    NZERO = NZERO + 1
         GO TO 50
   30    NPOS = NPOS + 1
   50 CONTINUE
      RETURN
      END
