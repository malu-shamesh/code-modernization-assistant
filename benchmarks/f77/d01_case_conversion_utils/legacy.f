C     CASEUT - CHARACTER CASE CONVERSION UTILITIES
C
C     TOUPPR  COPY TEXT TO RES, FOLDING LOWER CASE LETTERS TO UPPER CASE
C     TOLOWR  COPY TEXT TO RES, FOLDING UPPER CASE LETTERS TO LOWER CASE
C     SWAPCS  COPY TEXT TO RES, EXCHANGING THE CASE OF EVERY LETTER
C     NUPPER  COUNT THE UPPER CASE LETTERS OF A STRING
C     TITLEC  CAPITALISE THE FIRST LETTER OF EVERY BLANK SEPARATED WORD
C
C     THE CODE ASSUMES THE ASCII COLLATING SEQUENCE, WHERE EACH LOWER
C     CASE LETTER FOLLOWS ITS UPPER CASE PARTNER BY EXACTLY 32.
C     TEXT LONGER THAN 40 CHARACTERS IS TRUNCATED AND SHORTER TEXT IS
C     PADDED WITH BLANKS (THE STANDARD CHARACTER ASSIGNMENT RULES).
C
      SUBROUTINE TOUPPR(TEXT, RES)
      CHARACTER*(*) TEXT
      CHARACTER*40 RES
      INTEGER I, IC, N
      RES = ' '
      N = MIN(LEN(TEXT), 40)
      DO 10 I = 1, N
         IC = ICHAR(TEXT(I:I))
         IF (IC .GE. 97 .AND. IC .LE. 122) IC = IC - 32
         RES(I:I) = CHAR(IC)
   10 CONTINUE
      RETURN
      END
C
      SUBROUTINE TOLOWR(TEXT, RES)
      CHARACTER*(*) TEXT
      CHARACTER*40 RES
      INTEGER I, IC, N
      RES = ' '
      N = MIN(LEN(TEXT), 40)
      DO 10 I = 1, N
         IC = ICHAR(TEXT(I:I))
         IF (IC .GE. 65 .AND. IC .LE. 90) IC = IC + 32
         RES(I:I) = CHAR(IC)
   10 CONTINUE
      RETURN
      END
C
      SUBROUTINE SWAPCS(TEXT, RES)
      CHARACTER*(*) TEXT
      CHARACTER*40 RES
      INTEGER I, IC, N
      RES = ' '
      N = MIN(LEN(TEXT), 40)
      DO 10 I = 1, N
         IC = ICHAR(TEXT(I:I))
         IF (IC .GE. 97 .AND. IC .LE. 122) THEN
            IC = IC - 32
         ELSE IF (IC .GE. 65 .AND. IC .LE. 90) THEN
            IC = IC + 32
         END IF
         RES(I:I) = CHAR(IC)
   10 CONTINUE
      RETURN
      END
C
      INTEGER FUNCTION NUPPER(TEXT)
      CHARACTER*(*) TEXT
      INTEGER I, IC, NCOUNT
      NCOUNT = 0
      DO 10 I = 1, LEN(TEXT)
         IC = ICHAR(TEXT(I:I))
         IF (IC .GE. 65 .AND. IC .LE. 90) NCOUNT = NCOUNT + 1
   10 CONTINUE
      NUPPER = NCOUNT
      RETURN
      END
C
C     TITLEC RELIES ON THE IMPLICIT TYPING RULE FOR I, IC AND N
      SUBROUTINE TITLEC(TEXT, RES)
      CHARACTER*(*) TEXT
      CHARACTER*40 RES
      LOGICAL NEWWD
      NEWWD = .TRUE.
      RES = ' '
      N = MIN(LEN(TEXT), 40)
      DO 10 I = 1, N
         IC = ICHAR(TEXT(I:I))
         IF (TEXT(I:I) .EQ. ' ') THEN
            NEWWD = .TRUE.
         ELSE
            IF (NEWWD .AND. IC .GE. 97 .AND. IC .LE. 122) IC = IC - 32
            IF (.NOT. NEWWD .AND. IC .GE. 65 .AND. IC .LE. 90)
     &         IC = IC + 32
            NEWWD = .FALSE.
         END IF
         RES(I:I) = CHAR(IC)
   10 CONTINUE
      RETURN
      END
