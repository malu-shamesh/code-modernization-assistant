C     SIGNAL CONDITIONING WITH LOCAL "SUBROUTINES" REACHED BY ASSIGNED
C     GO TO.  THE ORIGINAL AUTHORS HAD NO INTERNAL PROCEDURES, SO A
C     SHARED BLOCK OF CODE WAS ENTERED WITH  ASSIGN <RETURN LABEL> TO
C     IRET  /  GO TO <BLOCK>  AND LEFT WITH  GO TO IRET, (LABELS).
C
C     SATACC  SATURATING ACCUMULATOR: CLIP EACH SAMPLE, ADD IT TO THE
C             RUNNING TOTAL, CLIP THE TOTAL
C     RUNLEN  RUN-LENGTH STATISTICS OF AN INTEGER SEQUENCE
C
      SUBROUTINE SATACC(N, IX, LO, HI, ALO, AHI, NCLIP, ISUM)
C
C     EVERY SAMPLE IX(I) IS CLIPPED INTO [LO, HI] AND ADDED TO ISUM,
C     AND ISUM IS THEN CLIPPED INTO [ALO, AHI].  NCLIP COUNTS ALL
C     CLIPPING EVENTS OF BOTH KINDS.  CALLERS GUARANTEE LO .LE. HI AND
C     ALO .LE. AHI.
C
      INTEGER N, IX(N), LO, HI, ALO, AHI, NCLIP, ISUM
      INTEGER V, VLO, VHI, I, IRET
      NCLIP = 0
      ISUM = 0
      I = 0
  100 I = I + 1
      IF (I .GT. N) RETURN
      V = IX(I)
      VLO = LO
      VHI = HI
      ASSIGN 120 TO IRET
      GO TO 700
  120 ISUM = ISUM + V
      V = ISUM
      VLO = ALO
      VHI = AHI
      ASSIGN 140 TO IRET
      GO TO 700
  140 ISUM = V
      GO TO 100
C
C     LOCAL BLOCK: CLAMP V INTO [VLO, VHI], COUNT THE EVENT
C
  700 IF (V .GE. VLO) GO TO 710
      V = VLO
      NCLIP = NCLIP + 1
      GO TO 730
  710 IF (V .LE. VHI) GO TO 730
      V = VHI
      NCLIP = NCLIP + 1
  730 GO TO IRET, (120, 140)
      END
C
      SUBROUTINE RUNLEN(N, IX, NRUN, LONGST, ISTART)
C
C     NRUN    NUMBER OF MAXIMAL RUNS OF EQUAL NEIGHBOURING VALUES
C     LONGST  LENGTH OF THE LONGEST RUN
C     ISTART  INDEX WHERE THE FIRST LONGEST RUN BEGINS
C     ALL THREE ARE ZERO FOR AN EMPTY SEQUENCE.
C
      INTEGER N, IX(N), NRUN, LONGST, ISTART
      INTEGER I, IBEG, ILEN, IRET
      NRUN = 0
      LONGST = 0
      ISTART = 0
      IF (N .LE. 0) RETURN
      IBEG = 1
      I = 1
   10 I = I + 1
      IF (I .GT. N) GO TO 30
      IF (IX(I) .EQ. IX(I-1)) GO TO 10
      ASSIGN 20 TO IRET
      GO TO 90
   20 IBEG = I
      GO TO 10
   30 ASSIGN 40 TO IRET
      GO TO 90
   40 RETURN
C
C     LOCAL BLOCK: CLOSE THE RUN IBEG .. I-1
C
   90 NRUN = NRUN + 1
      ILEN = I - IBEG
      IF (ILEN .LE. LONGST) GO TO 95
      LONGST = ILEN
      ISTART = IBEG
   95 GO TO IRET, (20, 40)
      END
