C     WEEKLY PAYROLL REPORT FOR A SMALL SHOP
C
C     PAYRPT  MAIN PROGRAM: ONE REPORT LINE PER EMPLOYEE, TOTALS, AND
C             THE AVERAGE AND LARGEST NET PAY SPLIT INTO DOLLARS
C             AND CENTS
C     PAYCLC  GROSS PAY AND WITHHOLDING FOR ONE EMPLOYEE
C     SPLITC  SPLITS A MONEY AMOUNT INTO SIGN, DOLLARS AND CENTS
C
      PROGRAM PAYRPT
      INTEGER NEMP
      PARAMETER (NEMP = 5)
      INTEGER ID(NEMP), IGRADE(NEMP)
      INTEGER I, NPAID, NREJ, ISG, IDOL, ICENT
      REAL HOURS(NEMP), RATE(NEMP)
      REAL GROSS, TAX, NET, TGROSS, TTAX, TNET, AVG, BEST
      DATA ID /101, 102, 103, 104, 105/
      DATA IGRADE /1, 2, 3, 7, 2/
      DATA HOURS /40.0, 44.0, 42.0, 40.0, 8.0/
      DATA RATE /12.5, 20.0, 25.0, 10.0, 9.75/
      NPAID = 0
      NREJ = 0
      TGROSS = 0.0
      TTAX = 0.0
      TNET = 0.0
      BEST = 0.0
      WRITE (*, 900)
      DO 100 I = 1, NEMP
         CALL PAYCLC(HOURS(I), RATE(I), IGRADE(I), GROSS, TAX, *80)
         NET = GROSS - TAX
         NPAID = NPAID + 1
         TGROSS = TGROSS + GROSS
         TTAX = TTAX + TAX
         TNET = TNET + NET
         IF (NET .GT. BEST) BEST = NET
         WRITE (*, 910) ID(I), GROSS, TAX, NET
         GO TO 100
   80    NREJ = NREJ + 1
         WRITE (*, 920) ID(I), IGRADE(I)
  100 CONTINUE
      WRITE (*, 930) TGROSS, TTAX, TNET
      WRITE (*, 940) NPAID, NREJ
      IF (NPAID .EQ. 0) STOP
      AVG = TNET / FLOAT(NPAID)
      CALL SPLITC(AVG, ISG, IDOL, ICENT)
      WRITE (*, 950) IDOL, ICENT
      CALL SPLITC(BEST, ISG, IDOL, ICENT)
      WRITE (*, 960) IDOL, ICENT
  900 FORMAT (1X, 'EMP', 5X, 'GROSS', 7X, 'TAX', 7X, 'NET')
  910 FORMAT (1X, I3, 3F10.2)
  920 FORMAT (1X, I3, 2X, 'BAD GRADE ', I2)
  930 FORMAT (1X, 'TOT', 3F10.2)
  940 FORMAT (1X, 'PAID', I3, 2X, 'REJECTED', I3)
  950 FORMAT (1X, 'AVG NET ', I6, '.', I2.2)
  960 FORMAT (1X, 'TOP NET ', I6, '.', I2.2)
      END
C
      SUBROUTINE PAYCLC(HOURS, RATE, IGRADE, GROSS, TAX, *)
C
C     OVERTIME (HOURS ABOVE 40) IS PAID AT 1.0, 1.5 OR 2.0 TIMES THE
C     RATE FOR GRADES 1, 2 AND 3.  WITHHOLDING IS
C        TAXTAB(1,G) * (GROSS - TAXTAB(2,G))      NEVER BELOW ZERO
C     WITH THE TABLE (RATE, ALLOWANCE) PER GRADE G KEPT AS A FLAT LIST
C     IN TAXFLT, WHICH IS THE SAME STORAGE AS THE 2 BY 3 TABLE.
C     RETURN 1  GRADE NOT IN 1 .. 3 (GROSS AND TAX ARE SET TO ZERO)
C
      REAL HOURS, RATE, GROSS, TAX
      INTEGER IGRADE
      REAL TAXTAB(2,3), TAXFLT(6), OTMULT, REG, OVT
      EQUIVALENCE (TAXTAB(1,1), TAXFLT(1))
      DATA TAXFLT /0.125, 0.0, 0.25, 100.0, 0.375, 300.0/
      GROSS = 0.0
      TAX = 0.0
      GO TO (10, 20, 30), IGRADE
      RETURN 1
   10 OTMULT = 1.0
      GO TO 40
   20 OTMULT = 1.5
      GO TO 40
   30 OTMULT = 2.0
   40 REG = AMIN1(HOURS, 40.0) * RATE
      OVT = 0.0
      IF (HOURS - 40.0) 60, 60, 50
   50 OVT = (HOURS - 40.0) * RATE * OTMULT
   60 GROSS = REG + OVT
      TAX = TAXTAB(1, IGRADE) * (GROSS - TAXTAB(2, IGRADE))
      IF (TAX) 70, 80, 80
   70 TAX = 0.0
   80 RETURN
      END
C
      SUBROUTINE SPLITC(AMT, ISG, IDOL, ICENT)
C
C     AMT ROUNDED TO WHOLE CENTS (HALF AWAY FROM ZERO).
C     ISG    -1 WHEN THE ROUNDED AMOUNT IS NEGATIVE, ELSE +1
C     IDOL   WHOLE DOLLARS, TRUNCATED TOWARD ZERO (SO IT CARRIES THE
C            SIGN, EXCEPT THAT IT IS 0 FOR AMOUNTS BETWEEN -1 AND 1)
C     ICENT  CENTS, 0 .. 99, ALWAYS NON-NEGATIVE
C
      REAL AMT
      INTEGER ISG, IDOL, ICENT, ICT
      ICT = NINT(AMT * 100.0)
      ISG = 1
      IF (ICT .LT. 0) ISG = -1
      IDOL = ICT / 100
      ICENT = IABS(MOD(ICT, 100))
      RETURN
      END
