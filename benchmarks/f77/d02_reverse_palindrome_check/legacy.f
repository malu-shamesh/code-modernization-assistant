C     STRUTL - STRING REVERSAL AND PALINDROME TEST
C
C     LASTNB  POSITION OF THE LAST NON-BLANK CHARACTER (0 IF ALL BLANK)
C     ISALNM  TRUE FOR A DIGIT OR A LETTER OF EITHER CASE
C     FOLDUP  UPPER CASE EQUIVALENT OF A SINGLE CHARACTER
C     REVERS  REVERSE THE TEXT UP TO ITS LAST NON-BLANK CHARACTER
C     ISPALN  TRUE WHEN THE LETTERS AND DIGITS OF TEXT READ THE SAME
C             FORWARDS AND BACKWARDS, IGNORING CASE, BLANKS, PUNCTUATION
C
      INTEGER FUNCTION LASTNB(S)
      CHARACTER*(*) S
      INTEGER I
      DO 10 I = LEN(S), 1, -1
         IF (S(I:I) .NE. ' ') THEN
            LASTNB = I
            RETURN
         END IF
   10 CONTINUE
      LASTNB = 0
      RETURN
      END
C
      LOGICAL FUNCTION ISALNM(C)
      CHARACTER*1 C
      INTEGER IC
      IC = ICHAR(C)
      ISALNM = (IC .GE. 48 .AND. IC .LE. 57) .OR.
     &         (IC .GE. 65 .AND. IC .LE. 90) .OR.
     &         (IC .GE. 97 .AND. IC .LE. 122)
      RETURN
      END
C
      CHARACTER*1 FUNCTION FOLDUP(C)
      CHARACTER*1 C
      INTEGER IC
      IC = ICHAR(C)
      IF (IC .GE. 97 .AND. IC .LE. 122) IC = IC - 32
      FOLDUP = CHAR(IC)
      RETURN
      END
C
C     LEADING BLANKS OF TEXT BECOME TRAILING BLANKS OF RES.  AT MOST
C     THE FIRST 40 CHARACTERS OF TEXT ARE REVERSED.
      SUBROUTINE REVERS(TEXT, RES)
      CHARACTER*(*) TEXT
      CHARACTER*40 RES
      INTEGER LASTNB, I, N
      RES = ' '
      N = MIN(LASTNB(TEXT), 40)
      DO 20 I = 1, N
         RES(I:I) = TEXT(N-I+1:N-I+1)
   20 CONTINUE
      RETURN
      END
C
      LOGICAL FUNCTION ISPALN(TEXT)
      CHARACTER*(*) TEXT
      LOGICAL ISALNM
      CHARACTER*1 FOLDUP
      INTEGER I, J
      I = 1
      J = LEN(TEXT)
C     MOVE I UP AND J DOWN TO THE NEXT LETTER OR DIGIT, THEN COMPARE
   30 IF (I .GE. J) GO TO 50
      IF (ISALNM(TEXT(I:I))) GO TO 35
      I = I + 1
      GO TO 30
   35 IF (ISALNM(TEXT(J:J))) GO TO 40
      J = J - 1
      GO TO 30
   40 IF (FOLDUP(TEXT(I:I)) .NE. FOLDUP(TEXT(J:J))) THEN
         ISPALN = .FALSE.
         RETURN
      END IF
      I = I + 1
      J = J - 1
      GO TO 30
   50 ISPALN = .TRUE.
      RETURN
      END
