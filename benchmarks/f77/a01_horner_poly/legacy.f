C     POLYNOMIAL UTILITIES BASED ON HORNER'S NESTED MULTIPLICATION
C
C     COEFFICIENTS ARE STORED IN ASCENDING ORDER OF POWER:
C        P(X) = C(1) + C(2)*X + C(3)*X**2 + ... + C(N+1)*X**N
C     SO A POLYNOMIAL OF DEGREE N NEEDS N+1 COEFFICIENTS.
C
C     HORNER - VALUE OF P(X)
      DOUBLE PRECISION FUNCTION HORNER(N, C, X)
      INTEGER N
      DOUBLE PRECISION C(*), X
      DOUBLE PRECISION P
C     START WITH THE LEADING COEFFICIENT AND WORK DOWNWARD
      P = C(N+1)
      DO 10 I = N, 1, -1
         P = P*X + C(I)
   10 CONTINUE
      HORNER = P
      RETURN
      END
C
C     POLDER - VALUE AND FIRST DERIVATIVE IN A SINGLE SWEEP
C     ON RETURN P = P(X) AND DP = P'(X).
      SUBROUTINE POLDER(N, C, X, P, DP)
      INTEGER N
      DOUBLE PRECISION C(*), X, P, DP
      P = C(N+1)
      DP = 0.0D0
      DO 20 I = N, 1, -1
         DP = DP*X + P
         P = P*X + C(I)
   20 CONTINUE
      RETURN
      END
C
C     DEFLAT - DIVIDE P(X) BY (X - R) BY SYNTHETIC DIVISION.
C     Q(1..N) RECEIVES THE COEFFICIENTS OF THE QUOTIENT (DEGREE N-1)
C     AND REM IS THE REMAINDER, WHICH EQUALS P(R).  REQUIRES N >= 1.
      SUBROUTINE DEFLAT(N, C, R, Q, REM)
      INTEGER N
      DOUBLE PRECISION C(*), R, Q(*), REM
      Q(N) = C(N+1)
      DO 30 I = N-1, 1, -1
         Q(I) = C(I+1) + R*Q(I+1)
   30 CONTINUE
      REM = C(1) + R*Q(1)
      RETURN
      END
