C     NUMERICAL QUADRATURE: COMPOSITE TRAPEZOID AND SIMPSON RULES,
C     AND A DRIVER THAT REFINES SIMPSON ESTIMATES UNTIL THEY AGREE.
C     F IS A USER FUNCTION OF ONE DOUBLE PRECISION ARGUMENT.
C
C     TRAPZ - TRAPEZOID RULE ON [A,B] WITH N PANELS (N >= 1)
      DOUBLE PRECISION FUNCTION TRAPZ(F, A, B, N)
      EXTERNAL F
      DOUBLE PRECISION F, A, B, H, S
      INTEGER N
      H = (B - A)/DBLE(N)
      S = 0.5D0*(F(A) + F(B))
      DO 10 I = 1, N-1
         S = S + F(A + DBLE(I)*H)
   10 CONTINUE
      TRAPZ = S*H
      RETURN
      END
C
C     SIMPSN - SIMPSON'S RULE ON [A,B].  THE NUMBER OF PANELS MUST
C     BE EVEN; AN ODD N IS INCREASED BY ONE AND THE CHANGED VALUE
C     IS HANDED BACK TO THE CALLER.
      DOUBLE PRECISION FUNCTION SIMPSN(F, A, B, N)
      EXTERNAL F
      DOUBLE PRECISION F, A, B, H, S
      INTEGER N
      IF (2*(N/2) .NE. N) N = N + 1
      H = (B - A)/DBLE(N)
      S = F(A) + F(B)
      DO 20 I = 1, N-1
         IF (MOD(I, 2) .EQ. 1) THEN
            S = S + 4.0D0*F(A + DBLE(I)*H)
         ELSE
            S = S + 2.0D0*F(A + DBLE(I)*H)
         END IF
   20 CONTINUE
      SIMPSN = S*H/3.0D0
      RETURN
      END
C
C     QUADEX - DOUBLE THE NUMBER OF PANELS, STARTING FROM 2, UNTIL TWO
C     SUCCESSIVE SIMPSON ESTIMATES DIFFER BY NO MORE THAN TOL.
C     VAL IS THE LATEST ESTIMATE AND NUSED THE PANEL COUNT OF IT.  IF
C     MORE THAN NMAX PANELS WOULD BE NEEDED, NUSED IS SET TO 0 AND
C     VAL IS THE LAST ESTIMATE THAT WAS COMPUTED.
      SUBROUTINE QUADEX(F, A, B, TOL, NMAX, VAL, NUSED)
      EXTERNAL F
      DOUBLE PRECISION F, A, B, TOL, VAL, OLD, SIMPSN
      INTEGER NMAX, NUSED, N
      N = 2
      OLD = SIMPSN(F, A, B, N)
   30 N = 2*N
      IF (N .GT. NMAX) GO TO 40
      VAL = SIMPSN(F, A, B, N)
      IF (DABS(VAL - OLD) .LE. TOL) GO TO 50
      OLD = VAL
      GO TO 30
   40 NUSED = 0
      VAL = OLD
      RETURN
   50 NUSED = N
      RETURN
      END
