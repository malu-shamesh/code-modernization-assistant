C     UNITCV - LENGTH UNIT CONVERSION DRIVEN BY A TABLE IN COMMON
C
C     THE BUILT-IN UNITS ARE LOADED BY BLOCK DATA UNITBD.  NAMES AND
C     FACTORS (METRES PER UNIT) LIVE IN SEPARATE COMMON BLOCKS BECAUSE
C     FORTRAN 77 FORBIDS MIXING CHARACTER AND NUMERIC STORAGE.
C
      BLOCK DATA UNITBD
      CHARACTER*4 UNAME(8)
      DOUBLE PRECISION FACT(8)
      INTEGER NUNIT
      COMMON /UNAMES/ UNAME
      COMMON /UFACTS/ FACT
      COMMON /UNCNT/ NUNIT
      DATA UNAME /'M   ', 'KM  ', 'CM  ', 'MM  ', 'IN  ', 'FT  ',
     &            2*'    '/
      DATA FACT /1.0D0, 1.0D3, 1.0D-2, 1.0D-3, 2.54D-2, 3.048D-1,
     &           2*0.0D0/
      DATA NUNIT /6/
      END
C
C     NUMBER OF UNITS CURRENTLY IN THE TABLE
      INTEGER FUNCTION UCNT()
      INTEGER NUNIT
      COMMON /UNCNT/ NUNIT
      UCNT = NUNIT
      RETURN
      END
C
C     TABLE INDEX OF A UNIT NAME, OR 0 WHEN IT IS NOT KNOWN
      INTEGER FUNCTION UFIND(NAME)
      CHARACTER*(*) NAME
      CHARACTER*4 UNAME(8)
      INTEGER NUNIT
      COMMON /UNAMES/ UNAME
      COMMON /UNCNT/ NUNIT
      UFIND = 0
      DO 10 I = 1, NUNIT
         IF (UNAME(I) .EQ. NAME) THEN
            UFIND = I
            RETURN
         END IF
   10 CONTINUE
      RETURN
      END
C
C     CONVERT X FROM UNIT CFROM TO UNIT CTO.
C     IERR = 0 OK, 1 UNKNOWN CFROM, 2 UNKNOWN CTO (RESULT IS THEN 0)
      DOUBLE PRECISION FUNCTION UCONV(X, CFROM, CTO, IERR)
      DOUBLE PRECISION X
      CHARACTER*(*) CFROM, CTO
      INTEGER IERR, UFIND
      DOUBLE PRECISION FACT(8)
      COMMON /UFACTS/ FACT
      UCONV = 0.0D0
      IERR = 0
      I = UFIND(CFROM)
      IF (I .EQ. 0) THEN
         IERR = 1
         RETURN
      END IF
      J = UFIND(CTO)
      IF (J .EQ. 0) THEN
         IERR = 2
         RETURN
      END IF
      UCONV = X * FACT(I) / FACT(J)
      RETURN
      END
C
C     ADD A UNIT.  IERR = 0 OK, 1 TABLE FULL, 2 FACTOR NOT POSITIVE,
C     3 NAME ALREADY PRESENT.  ONLY THE FIRST 4 CHARACTERS ARE KEPT.
      SUBROUTINE UADD(NAME, FACTOR, IERR)
      CHARACTER*(*) NAME
      DOUBLE PRECISION FACTOR
      INTEGER IERR, UFIND
      CHARACTER*4 UNAME(8)
      DOUBLE PRECISION FACT(8)
      INTEGER NUNIT
      COMMON /UNAMES/ UNAME
      COMMON /UFACTS/ FACT
      COMMON /UNCNT/ NUNIT
      IERR = 0
      IF (FACTOR .LE. 0.0D0) THEN
         IERR = 2
      ELSE IF (UFIND(NAME) .NE. 0) THEN
         IERR = 3
      ELSE IF (NUNIT .GE. 8) THEN
         IERR = 1
      ELSE
         NUNIT = NUNIT + 1
         UNAME(NUNIT) = NAME
         FACT(NUNIT) = FACTOR
      END IF
      RETURN
      END
C
C     DROP EVERY USER-ADDED UNIT AGAIN, KEEPING THE SIX BUILT-IN ONES
      SUBROUTINE URESET
      CHARACTER*4 UNAME(8)
      DOUBLE PRECISION FACT(8)
      INTEGER NUNIT
      COMMON /UNAMES/ UNAME
      COMMON /UFACTS/ FACT
      COMMON /UNCNT/ NUNIT
      DO 10 I = 7, 8
         UNAME(I) = ' '
         FACT(I) = 0.0D0
   10 CONTINUE
      NUNIT = 6
      RETURN
      END
