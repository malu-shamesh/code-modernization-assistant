C     GREATEST COMMON DIVISOR, LEAST COMMON MULTIPLE AND RELATED
C     INTEGER UTILITIES (EUCLID'S ALGORITHM)
C
C     IGCD - GCD OF TWO INTEGERS, ALWAYS >= 0.  IGCD(0,0) IS 0.
      INTEGER FUNCTION IGCD(M, N)
      INTEGER M, N, A, B, T
C     WORK ON ABSOLUTE VALUES SO MOD NEVER SEES A NEGATIVE OPERAND
      A = IABS(M)
      B = IABS(N)
   10 IF (B .EQ. 0) GO TO 20
      T = MOD(A, B)
      A = B
      B = T
      GO TO 10
   20 IGCD = A
      RETURN
      END
C
C     ILCM - LEAST COMMON MULTIPLE, ALWAYS >= 0; 0 IF EITHER IS 0
      INTEGER FUNCTION ILCM(M, N)
      INTEGER M, N, G
      IF (M .EQ. 0 .OR. N .EQ. 0) THEN
         ILCM = 0
         RETURN
      END IF
      G = IGCD(M, N)
C     DIVIDE BEFORE MULTIPLYING TO KEEP THE INTERMEDIATE SMALL
      ILCM = IABS(M/G*N)
      RETURN
      END
C
C     IGCDV - GCD OF THE FIRST N ELEMENTS OF IA (0 WHEN N .LE. 0)
      INTEGER FUNCTION IGCDV(N, IA)
      INTEGER N, IA(*)
      IGCDV = 0
      DO 30 I = 1, N
         IGCDV = IGCD(IGCDV, IA(I))
C        NOTHING CAN GO BELOW 1, SO STOP EARLY
         IF (IGCDV .EQ. 1) GO TO 40
   30 CONTINUE
   40 RETURN
      END
C
C     IMODP - MODULUS IN THE RANGE 0 .. P-1 FOR P > 0, UNLIKE MOD
C     WHICH GIVES THE REMAINDER THE SIGN OF THE DIVIDEND.
      INTEGER FUNCTION IMODP(A, P)
      INTEGER A, P, R
      R = MOD(A, P)
      IF (R .LT. 0) R = R + P
      IMODP = R
      RETURN
      END
C
C     REDUCE - REDUCE THE FRACTION NUM/DEN TO LOWEST TERMS IN PLACE.
C     THE DENOMINATOR IS MADE POSITIVE; 0/0 IS LEFT UNCHANGED.
      SUBROUTINE REDUCE(NUM, DEN)
      INTEGER NUM, DEN, G
      G = IGCD(NUM, DEN)
      IF (G .EQ. 0) RETURN
      NUM = NUM/G
      DEN = DEN/G
      IF (DEN .LT. 0) THEN
         NUM = -NUM
         DEN = -DEN
      END IF
      RETURN
      END
