C**********************************************************************
C     BINARY SEARCH ROUTINES FOR AN ASCENDING INTEGER TABLE
C
C     IBSRCH  LOCATES KEY AND COUNTS THE PROBES USED
C     ILBND   FIRST INDEX I WITH IA(I) .GE. KEY  (LOWER BOUND)
C     ICOUNT  NUMBER OF ELEMENTS EQUAL TO KEY
C
C     THE TABLE IA(1..N) MUST BE SORTED ASCENDING.  NO CHECK IS MADE.
C**********************************************************************
C
C     IBSRCH - EXACT-MATCH SEARCH WITH EARLY EXIT
C       RESULT  INDEX OF A MATCHING ELEMENT, OR -(K) WHEN KEY IS ABSENT,
C               WHERE K IS THE INDEX AT WHICH KEY WOULD BE INSERTED
C       NPROBE  (OUTPUT) NUMBER OF ELEMENTS COMPARED WITH KEY
C
      INTEGER FUNCTION IBSRCH(N, KEY, IA, NPROBE)
      INTEGER N, KEY, NPROBE
      INTEGER IA(*)
C     LO, HI AND MID ARE TYPED BY THE I-N RULE
      NPROBE = 0
      LO = 1
      HI = N
   10 IF (LO .GT. HI) GO TO 30
      MID = (LO + HI) / 2
      NPROBE = NPROBE + 1
      IF (IA(MID) .EQ. KEY) GO TO 20
      IF (IA(MID) .LT. KEY) LO = MID + 1
      IF (IA(MID) .GT. KEY) HI = MID - 1
      GO TO 10
   20 IBSRCH = MID
      RETURN
   30 IBSRCH = -LO
      RETURN
      END
C
C     ILBND - LOWER BOUND.  THE INTERVAL [LO, HI) ALWAYS CONTAINS THE
C     ANSWER; IT IS HALVED UNTIL ONE INDEX IS LEFT.  RESULT N+1 MEANS
C     THAT EVERY ELEMENT IS SMALLER THAN KEY.
C
      INTEGER FUNCTION ILBND(N, KEY, IA)
      INTEGER N, KEY
      INTEGER IA(*)
      INTEGER LO, HI, MID
      LO = 1
      HI = N + 1
   10 IF (LO .GE. HI) GO TO 20
      MID = (LO + HI) / 2
      IF (IA(MID) .LT. KEY) THEN
         LO = MID + 1
      ELSE
         HI = MID
      END IF
      GO TO 10
   20 ILBND = LO
      RETURN
      END
C
C     ICOUNT - NUMBER OF OCCURRENCES OF KEY: THE LOWER BOUND OF KEY+1
C     MINUS THE LOWER BOUND OF KEY
C
      INTEGER FUNCTION ICOUNT(N, KEY, IA)
      INTEGER N, KEY
      INTEGER IA(*)
      INTEGER ILBND
      ICOUNT = ILBND(N, KEY + 1, IA) - ILBND(N, KEY, IA)
      RETURN
      END
