C     BITOPS - 32-BIT WORD UTILITIES AND A PACKED BIT SET
C
C     INTEGER IS A 32-BIT TWO'S COMPLEMENT WORD.  THE BIT INTRINSICS
C     ARE THE MIL-STD-1753 ONES; ISHFT IS A LOGICAL SHIFT (POSITIVE
C     LEFT, NEGATIVE RIGHT, ZERO FILL) AND DROPS BITS SHIFTED OUT.
C     BIT NUMBERS RUN FROM 0 (LEAST SIGNIFICANT) TO 31.
C
C     NUMBER OF ONE BITS IN THE WORD
      INTEGER FUNCTION BITCNT(IW)
      INTEGER IW, IT, NC
      NC = 0
      IT = IW
   10 IF (IT .EQ. 0) GO TO 20
      IF (IAND(IT, 1) .NE. 0) NC = NC + 1
      IT = ISHFT(IT, -1)
      GO TO 10
   20 BITCNT = NC
      RETURN
      END
C
C     REVERSE THE ORDER OF THE LOW NB BITS (0 .LE. NB .LE. 32)
      INTEGER FUNCTION BITREV(IW, NB)
      INTEGER IW, NB, IT, NN, IR
      NN = MAX0(0, MIN0(NB, 32))
      IT = IW
      IR = 0
      DO 10 J = 1, NN
         IR = IOR(ISHFT(IR, 1), IAND(IT, 1))
         IT = ISHFT(IT, -1)
   10 CONTINUE
      BITREV = IR
      RETURN
      END
C
C     BINARY TO GRAY CODE AND BACK
      INTEGER FUNCTION GRAYCD(IW)
      INTEGER IW
      GRAYCD = IEOR(IW, ISHFT(IW, -1))
      RETURN
      END
C
      INTEGER FUNCTION GRAYDC(IG)
      INTEGER IG, IB
      IB = IG
      DO 10 I = 0, 4
         IB = IEOR(IB, ISHFT(IB, -(2**I)))
   10 CONTINUE
      GRAYDC = IB
      RETURN
      END
C
C     ROTATE THE WORD LEFT BY ISH BITS (NEGATIVE ISH ROTATES RIGHT)
      INTEGER FUNCTION ROTL32(IW, ISH)
      INTEGER IW, ISH, N
      N = MOD(ISH, 32)
      IF (N .LT. 0) N = N + 32
      ROTL32 = IOR(ISHFT(IW, N), ISHFT(IW, N - 32))
      RETURN
      END
C
C     PACKED BIT SET IN IBITS(1..NW), BIT K IS BIT MOD(K,32) OF WORD
C     K/32+1.  IERR = 1 WHEN K IS OUTSIDE 0 .. 32*NW-1.
      SUBROUTINE BSSET(IBITS, NW, K, IERR)
      INTEGER IBITS(*), NW, K, IERR, IWD
      IERR = 0
      IF (K .LT. 0 .OR. K / 32 .GE. NW) THEN
         IERR = 1
         RETURN
      END IF
      IWD = K / 32 + 1
      IBITS(IWD) = IOR(IBITS(IWD), ISHFT(1, MOD(K, 32)))
      RETURN
      END
C
      SUBROUTINE BSCLR(IBITS, NW, K, IERR)
      INTEGER IBITS(*), NW, K, IERR, IWD
      IERR = 0
      IF (K .LT. 0 .OR. K / 32 .GE. NW) THEN
         IERR = 1
         RETURN
      END IF
      IWD = K / 32 + 1
      IBITS(IWD) = IAND(IBITS(IWD), NOT(ISHFT(1, MOD(K, 32))))
      RETURN
      END
C
      LOGICAL FUNCTION BSTEST(IBITS, NW, K)
      INTEGER IBITS(*), NW, K, IWD
      BSTEST = .FALSE.
      IF (K .LT. 0 .OR. K / 32 .GE. NW) RETURN
      IWD = K / 32 + 1
      BSTEST = IAND(IBITS(IWD), ISHFT(1, MOD(K, 32))) .NE. 0
      RETURN
      END
C
C     TOTAL NUMBER OF MEMBERS OF THE SET
      INTEGER FUNCTION BSCNT(IBITS, NW)
      INTEGER IBITS(*), NW, BITCNT, N
      N = 0
      DO 10 I = 1, NW
         N = N + BITCNT(IBITS(I))
   10 CONTINUE
      BSCNT = N
      RETURN
      END
C
C     SMALLEST MEMBER NOT BELOW K0, OR -1 WHEN THERE IS NONE
      INTEGER FUNCTION BSNEXT(IBITS, NW, K0)
      INTEGER IBITS(*), NW, K0
      LOGICAL BSTEST
      DO 10 K = MAX0(K0, 0), 32*NW - 1
         IF (BSTEST(IBITS, NW, K)) THEN
            BSNEXT = K
            RETURN
         END IF
   10 CONTINUE
      BSNEXT = -1
      RETURN
      END
