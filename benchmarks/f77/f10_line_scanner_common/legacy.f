C     LINESC - TOKEN SCANNER OVER A LINE HELD IN COMMON
C
C     SCINIT LOADS A LINE (KEPT AS CHARACTER*40) INTO COMMON AND
C     RESETS THE SCAN POSITION.  SCNEXT THEN RETURNS ONE TOKEN PER
C     CALL, CLASSIFIED AS 1 INTEGER, 2 IDENTIFIER, 3 ANY SINGLE OTHER
C     CHARACTER.  AT THE END OF THE LINE IT TAKES ALTERNATE RETURN 1.
C     TOKENS ARE CUT TO 12 CHARACTERS BUT THE SCAN POSITION STILL
C     MOVES PAST THE WHOLE TOKEN.  CHARACTER AND INTEGER STORAGE ARE
C     IN SEPARATE COMMON BLOCKS, AS FORTRAN 77 REQUIRES.
C
      SUBROUTINE SCINIT(LINE)
      CHARACTER*(*) LINE
      CHARACTER*40 BUF
      INTEGER IPOS, ILEN
      COMMON /SCNBUF/ BUF
      COMMON /SCNPTR/ IPOS, ILEN
      BUF = LINE
      ILEN = 40
   10 IF (ILEN .EQ. 0) GO TO 20
      IF (BUF(ILEN:ILEN) .NE. ' ') GO TO 20
      ILEN = ILEN - 1
      GO TO 10
   20 IPOS = 1
      RETURN
      END
C
C     CURRENT SCAN POSITION (1 = FIRST CHARACTER OF THE LINE)
      INTEGER FUNCTION SCPOS()
      INTEGER IPOS, ILEN
      COMMON /SCNPTR/ IPOS, ILEN
      SCPOS = IPOS
      RETURN
      END
C
      SUBROUTINE SCNEXT(TOK, ITYPE, *)
      CHARACTER*12 TOK
      INTEGER ITYPE
      CHARACTER*40 BUF
      INTEGER IPOS, ILEN, IC, ICLS, J
      COMMON /SCNBUF/ BUF
      COMMON /SCNPTR/ IPOS, ILEN
      TOK = ' '
      ITYPE = 0
C     SKIP BLANKS; THE ARITHMETIC IF TESTS WHETHER TEXT IS LEFT
   10 IF (IPOS - ILEN) 20, 20, 90
   20 IF (BUF(IPOS:IPOS) .NE. ' ') GO TO 30
      IPOS = IPOS + 1
      GO TO 10
   30 IC = ICHAR(BUF(IPOS:IPOS))
      ICLS = 3
      IF (IC .GE. 48 .AND. IC .LE. 57) ICLS = 1
      IF ((IC .GE. 65 .AND. IC .LE. 90) .OR.
     &    (IC .GE. 97 .AND. IC .LE. 122)) ICLS = 2
      J = IPOS + 1
      GO TO (40, 50, 70), ICLS
C     INTEGER: DIGITS ONLY
   40 IF (J .GT. ILEN) GO TO 70
      IC = ICHAR(BUF(J:J))
      IF (IC .LT. 48 .OR. IC .GT. 57) GO TO 70
      J = J + 1
      GO TO 40
C     IDENTIFIER: A LETTER FOLLOWED BY LETTERS AND DIGITS
   50 IF (J .GT. ILEN) GO TO 70
      IC = ICHAR(BUF(J:J))
      IF (IC .GE. 48 .AND. IC .LE. 57) GO TO 60
      IF ((IC .GE. 65 .AND. IC .LE. 90) .OR.
     &    (IC .GE. 97 .AND. IC .LE. 122)) GO TO 60
      GO TO 70
   60 J = J + 1
      GO TO 50
   70 TOK = BUF(IPOS:J-1)
      ITYPE = ICLS
      IPOS = J
      RETURN
   90 RETURN 1
      END
C
C     VALUE OF A DIGIT STRING UP TO THE FIRST BLANK (AT MOST NINE
C     DIGITS), OR -1 WHEN IT HOLDS A CHARACTER THAT IS NOT A DIGIT
      INTEGER FUNCTION SCINT(TOK)
      CHARACTER*(*) TOK
      INTEGER N, IC
      N = 0
      DO 10 I = 1, LEN(TOK)
         IF (TOK(I:I) .EQ. ' ') GO TO 20
         IC = ICHAR(TOK(I:I)) - 48
         IF (IC .LT. 0 .OR. IC .GT. 9) THEN
            SCINT = -1
            RETURN
         END IF
         N = 10 * N + IC
   10 CONTINUE
   20 SCINT = N
      RETURN
      END
C
C     COUNT THE TOKENS OF EACH CLASS IN A LINE
      SUBROUTINE SCTALL(LINE, NNUM, NID, NOP)
      CHARACTER*(*) LINE
      INTEGER NNUM, NID, NOP, ITYPE
      CHARACTER*12 TOK
      CALL SCINIT(LINE)
      NNUM = 0
      NID = 0
      NOP = 0
   10 CALL SCNEXT(TOK, ITYPE, *90)
      IF (ITYPE .EQ. 1) NNUM = NNUM + 1
      IF (ITYPE .EQ. 2) NID = NID + 1
      IF (ITYPE .EQ. 3) NOP = NOP + 1
      GO TO 10
   90 RETURN
      END
C
C     SUM OF THE INTEGER TOKENS OF A LINE
      SUBROUTINE SCSUM(LINE, ISUM)
      CHARACTER*(*) LINE
      INTEGER ISUM, ITYPE, SCINT
      CHARACTER*12 TOK
      CALL SCINIT(LINE)
      ISUM = 0
   10 CALL SCNEXT(TOK, ITYPE, *90)
      IF (ITYPE .EQ. 1) ISUM = ISUM + SCINT(TOK)
      GO TO 10
   90 RETURN
      END
