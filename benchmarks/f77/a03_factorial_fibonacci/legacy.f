C     FACTORIALS, FIBONACCI NUMBERS AND BINOMIAL COEFFICIENTS
C
C     IFACT - N FACTORIAL AS A DEFAULT INTEGER.  13! DOES NOT FIT IN
C     32 BITS, SO -1 IS RETURNED FOR N < 0 OR N > MAXFAC.
      INTEGER FUNCTION IFACT(N)
      INTEGER N, K, P, MAXFAC
      PARAMETER (MAXFAC = 12)
      IFACT = -1
      IF (N .LT. 0 .OR. N .GT. MAXFAC) RETURN
      P = 1
      DO 10 K = 2, N
         P = P*K
   10 CONTINUE
      IFACT = P
      RETURN
      END
C
C     DFACT - N FACTORIAL IN DOUBLE PRECISION (EXACT UP TO 22!,
C     FINITE UP TO 170!).  N < 2 GIVES 1.
      DOUBLE PRECISION FUNCTION DFACT(N)
      INTEGER N, K
      DOUBLE PRECISION P
      P = 1.0D0
      DO 20 K = 2, N
         P = P*DBLE(K)
   20 CONTINUE
      DFACT = P
      RETURN
      END
C
C     FIBTAB - FILL F(1..N) WITH THE FIBONACCI NUMBERS 1, 1, 2, 3, 5
C     ... (F(1) = F(2) = 1).  NOTHING IS TOUCHED FOR N < 1.
      SUBROUTINE FIBTAB(N, F)
      INTEGER N, F(N)
      INTEGER I
      IF (N .LT. 1) RETURN
      F(1) = 1
      IF (N .EQ. 1) RETURN
      F(2) = 1
      DO 30 I = 3, N
         F(I) = F(I-1) + F(I-2)
   30 CONTINUE
      RETURN
      END
C
C     IBINOM - BINOMIAL COEFFICIENT C(N,K); 0 UNLESS 0 <= K <= N
      INTEGER FUNCTION IBINOM(N, K)
      INTEGER N, K, KK, I, R
      IBINOM = 0
      IF (K .LT. 0 .OR. K .GT. N) RETURN
C     USE THE SMALLER OF K AND N-K TO KEEP THE LOOP SHORT
      KK = MIN0(K, N-K)
      R = 1
      DO 40 I = 1, KK
C        AFTER STEP I, R = C(N-KK+I, I), SO THE DIVISION BY I IS
C        EXACT AT EVERY STEP, BUT ONLY IF IT IS DONE AFTER THE PRODUCT
         R = R*(N-KK+I)/I
   40 CONTINUE
      IBINOM = R
      RETURN
      END
