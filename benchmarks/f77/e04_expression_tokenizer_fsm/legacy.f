C     LEXER FOR ARITHMETIC EXPRESSIONS, WRITTEN AS A LABELLED STATE
C     MACHINE.  EVERY TOKEN IS RECORDED AS A KIND AND A PAIR OF
C     CHARACTER POSITIONS (FIRST, LAST) INSIDE THE INPUT LINE.
C
C     TOKEN KINDS    1  INTEGER   (DIGITS)
C                    2  REAL      (DIGITS WITH A POINT, OR .DIGITS)
C                    3  NAME      (LETTER, THEN LETTERS AND DIGITS)
C                    4  OPERATOR  (ONE OF  + - * / ^ = ( ) ,  )
C
C     TOKEN  SPLITS THE LINE INTO TOKENS
C     TOKINT VALUE OF AN INTEGER TOKEN
C     ICLASS CHARACTER CLASS USED BY THE SCANNER
C
      SUBROUTINE TOKEN(LINE, MAXTOK, KIND, ISTART, IEND, NTOK, IERR)
C
C     IERR   0  WHOLE LINE SCANNED
C           >0  POSITION OF THE CHARACTER THAT COULD NOT BE SCANNED
C           -1  MORE THAN MAXTOK TOKENS
C     NTOK IS THE NUMBER OF COMPLETE TOKENS STORED IN EITHER CASE.
C
      CHARACTER*(*) LINE
      INTEGER MAXTOK, KIND(*), ISTART(*), IEND(*), NTOK, IERR
      INTEGER N, I, ICLS, ICLASS
      NTOK = 0
      IERR = 0
      N = LEN(LINE)
   10 IF (N .EQ. 0) RETURN
      IF (LINE(N:N) .NE. ' ') GO TO 20
      N = N - 1
      GO TO 10
   20 I = 1
C     TOP OF THE SCAN LOOP: SKIP BLANKS, THEN DISPATCH ON THE CLASS
   30 IF (I .GT. N) RETURN
      IF (LINE(I:I) .NE. ' ') GO TO 40
      I = I + 1
      GO TO 30
   40 IF (NTOK .GE. MAXTOK) GO TO 900
      ICLS = ICLASS(LINE(I:I))
      GO TO (100, 200, 300, 400), ICLS
      IERR = I
      RETURN
C     NUMBER THAT STARTS WITH A DIGIT
  100 NTOK = NTOK + 1
      KIND(NTOK) = 1
      ISTART(NTOK) = I
  110 I = I + 1
      IF (I .GT. N) GO TO 190
      ICLS = ICLASS(LINE(I:I))
      IF (ICLS .EQ. 1) GO TO 110
      IF (ICLS .NE. 4) GO TO 190
      KIND(NTOK) = 2
C     FRACTION DIGITS (ALSO ENTERED FROM THE LEADING-POINT CASE)
  120 I = I + 1
      IF (I .GT. N) GO TO 190
      IF (ICLASS(LINE(I:I)) .EQ. 1) GO TO 120
  190 IEND(NTOK) = I - 1
      GO TO 30
C     NAME
  200 NTOK = NTOK + 1
      KIND(NTOK) = 3
      ISTART(NTOK) = I
  210 I = I + 1
      IF (I .GT. N) GO TO 190
      ICLS = ICLASS(LINE(I:I))
      IF (ICLS .EQ. 1 .OR. ICLS .EQ. 2) GO TO 210
      GO TO 190
C     OPERATOR
  300 NTOK = NTOK + 1
      KIND(NTOK) = 4
      ISTART(NTOK) = I
      IEND(NTOK) = I
      I = I + 1
      GO TO 30
C     A POINT MUST BE FOLLOWED BY A DIGIT
  400 IF (I .EQ. N) GO TO 910
      IF (ICLASS(LINE(I+1:I+1)) .NE. 1) GO TO 910
      NTOK = NTOK + 1
      KIND(NTOK) = 2
      ISTART(NTOK) = I
      GO TO 120
  900 IERR = -1
      RETURN
  910 IERR = I
      RETURN
      END
C
      SUBROUTINE TOKINT(LINE, I1, I2, IVAL)
C     DECIMAL VALUE OF THE DIGITS IN LINE(I1:I2)
      CHARACTER*(*) LINE
      INTEGER I1, I2, IVAL, I
      IVAL = 0
      I = I1
   10 IF (I .GT. I2) RETURN
      IVAL = IVAL * 10 + ICHAR(LINE(I:I)) - ICHAR('0')
      I = I + 1
      GO TO 10
      END
C
      INTEGER FUNCTION ICLASS(C)
C     1 DIGIT, 2 LETTER, 3 OPERATOR, 4 DECIMAL POINT, 0 ANYTHING ELSE
      CHARACTER*1 C
      ICLASS = 0
      IF (C .GE. '0' .AND. C .LE. '9') ICLASS = 1
      IF (C .GE. 'A' .AND. C .LE. 'Z') ICLASS = 2
      IF (C .GE. 'a' .AND. C .LE. 'z') ICLASS = 2
      IF (INDEX('+-*/^=(),', C) .GT. 0) ICLASS = 3
      IF (C .EQ. '.') ICLASS = 4
      RETURN
      END
