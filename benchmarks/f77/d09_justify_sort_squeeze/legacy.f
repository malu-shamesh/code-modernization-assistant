C     TXTFMT - TEXT FORMATTING AND SORTING UTILITIES
C
C     ORDER   -1, 0 OR +1 AS A PRECEDES, EQUALS OR FOLLOWS B.  THE
C             SHORTER STRING IS PADDED WITH BLANKS, SO THE CHARACTERS
C             BELOW A BLANK IN THE COLLATING SEQUENCE COUNT AS SMALLER
C             THAN THE MISSING ONES.
C     JUSTFY  PLACE THE TRIMMED TEXT IN A FIELD OF WIDTH CHARACTERS OF
C             RES: MODE 1 LEFT, 2 RIGHT, 3 CENTRED, OTHERS ACT AS 1.
C             TEXT WIDER THAN THE FIELD IS CUT ON THE RIGHT.
C     SORTNM  SORT THE FIRST N NAMES INTO ASCENDING ORDER (BUBBLE SORT)
C     SQUEEZ  DROP LEADING BLANKS AND REDUCE EVERY RUN OF BLANKS TO ONE
C
      INTEGER FUNCTION ORDER(A, B)
      CHARACTER*(*) A, B
      IF (A .LT. B) THEN
         ORDER = -1
      ELSE IF (A .GT. B) THEN
         ORDER = 1
      ELSE
         ORDER = 0
      END IF
      RETURN
      END
C
      SUBROUTINE JUSTFY(TEXT, MODE, WIDTH, RES)
      CHARACTER*(*) TEXT
      INTEGER MODE, WIDTH
      CHARACTER*40 RES
      INTEGER NW, IFIRST, ILAST, LC, IS, I
      RES = ' '
      NW = MAX(1, MIN(WIDTH, 40))
C     FIRST AND LAST NON-BLANK CHARACTER OF TEXT
      IFIRST = 0
      ILAST = 0
      DO 10 I = 1, LEN(TEXT)
         IF (TEXT(I:I) .NE. ' ') THEN
            IF (IFIRST .EQ. 0) IFIRST = I
            ILAST = I
         END IF
   10 CONTINUE
      IF (IFIRST .EQ. 0) RETURN
      LC = MIN(ILAST - IFIRST + 1, NW)
      IF (MODE .EQ. 2) THEN
         IS = NW - LC + 1
      ELSE IF (MODE .EQ. 3) THEN
         IS = (NW - LC) / 2 + 1
      ELSE
         IS = 1
      END IF
      RES(IS:IS+LC-1) = TEXT(IFIRST:IFIRST+LC-1)
      RETURN
      END
C
C     THE OUTER AND INNER DO LOOPS SHARE THE TERMINAL STATEMENT 20
      SUBROUTINE SORTNM(NAMES, N)
      INTEGER N
      CHARACTER*12 NAMES(*), TEMP
      INTEGER I, J
      DO 20 I = 1, N - 1
      DO 20 J = 1, N - I
         IF (NAMES(J) .GT. NAMES(J+1)) THEN
            TEMP = NAMES(J)
            NAMES(J) = NAMES(J+1)
            NAMES(J+1) = TEMP
         END IF
   20 CONTINUE
      RETURN
      END
C
C     THE WORK BUFFER BUF IS ALSO ADDRESSED CHARACTER BY CHARACTER
C     THROUGH THE ARRAY CH.  ONLY THE FIRST 30 CHARACTERS ARE KEPT.
      SUBROUTINE SQUEEZ(TEXT, RES)
      CHARACTER*(*) TEXT
      CHARACTER*30 RES
      CHARACTER*30 BUF
      CHARACTER*1 CH(30)
      EQUIVALENCE (BUF, CH(1))
      LOGICAL PREVBL
      INTEGER I, K
      BUF = ' '
      K = 0
      PREVBL = .TRUE.
      DO 30 I = 1, LEN(TEXT)
         IF (TEXT(I:I) .EQ. ' ') THEN
            IF (.NOT. PREVBL .AND. K .LT. 30) THEN
               K = K + 1
               CH(K) = ' '
            END IF
            PREVBL = .TRUE.
         ELSE IF (K .LT. 30) THEN
            K = K + 1
            CH(K) = TEXT(I:I)
            PREVBL = .FALSE.
         END IF
   30 CONTINUE
      RES = BUF
      RETURN
      END
