C     ZERO FINDING BY BRACKETING SCAN AND BISECTION
C
C     ROOTSC  SCANS [A,B] IN STEPS OF H WITH A REAL DO VARIABLE UNTIL
C             F CHANGES SIGN, THEN BISECTS THE BRACKET.  EVERY LOOP
C             EXIT IS A JUMP TO ITS OWN LABEL.
C     FIXPT   FIXED-POINT ITERATION X = G(X) WITH THREE WAYS OUT
C     ISTEPS  ITERATION COUNT OF  DO X = A, B, H  (H MUST NOT BE 0)
C
      SUBROUTINE ROOTSC(F, A, B, H, TOL, MAXIT, ROOT, NIT, XEND, *, *)
C
C     H MAY BE NEGATIVE WHEN B .LT. A.  THE FIRST SAMPLE IS A ITSELF,
C     THE SCAN LOOP THEN VISITS A+H, A+2H, ... NOT BEYOND B.
C     ROOT   THE ZERO FOUND
C     NIT    NUMBER OF BISECTION STEPS (0 IF A SAMPLE HIT A ZERO)
C     XEND   VALUE OF THE SCAN VARIABLE WHEN THE SCAN STOPPED
C     RETURN 1  NO SIGN CHANGE FOUND, OR H IS ZERO
C     RETURN 2  MAXIT BISECTIONS DID NOT REACH THE TOLERANCE; ROOT IS
C               THE MIDPOINT OF THE CURRENT BRACKET
C
      EXTERNAL F
      DOUBLE PRECISION F, A, B, H, TOL, ROOT, XEND
      INTEGER MAXIT, NIT
      DOUBLE PRECISION X, XL, XR, XM, FL, FR, FM
      ROOT = 0.0D0
      NIT = 0
      XEND = A
      IF (H .EQ. 0.0D0) RETURN 1
      XL = A
      FL = F(XL)
      DO 10 X = A + H, B, H
         FR = F(X)
         IF (FL * FR) 30, 20, 8
    8    XL = X
         FL = FR
   10 CONTINUE
      XEND = X
      RETURN 1
C     A SAMPLE IS A ZERO: EITHER THE LEFT ONE (ONLY AT A) OR X
   20 IF (FL .EQ. 0.0D0) GO TO 25
      ROOT = X
      XEND = X
      RETURN
   25 ROOT = XL
      XEND = X
      RETURN
C     BRACKET [XL, X] FOUND, BISECT
   30 XR = X
      XEND = X
   40 IF (NIT .GE. MAXIT) GO TO 90
      XM = 0.5D0 * (XL + XR)
      FM = F(XM)
      NIT = NIT + 1
      IF (FL * FM) 50, 60, 55
   50 XR = XM
      GO TO 58
   55 XL = XM
      FL = FM
   58 IF (ABS(XR - XL) .GT. TOL) GO TO 40
      ROOT = 0.5D0 * (XL + XR)
      RETURN
   60 ROOT = XM
      RETURN
   90 ROOT = 0.5D0 * (XL + XR)
      RETURN 2
      END
C
      SUBROUTINE FIXPT(G, X0, TOL, MAXIT, XFIX, NIT, *, *)
C
C     X(K+1) = G(X(K)) STARTING AT X0.
C     RETURN 1  AN ITERATE EXCEEDS 1000 IN ABSOLUTE VALUE
C     RETURN 2  MAXIT ITERATIONS WITHOUT |X(K+1) - X(K)| .LE. TOL
C     XFIX IS THE LAST ITERATE IN EVERY CASE.
C
      EXTERNAL G
      DOUBLE PRECISION G, X0, TOL, XFIX, XN
      INTEGER MAXIT, NIT
      XFIX = X0
      NIT = 0
   10 IF (NIT .GE. MAXIT) RETURN 2
      XN = G(XFIX)
      NIT = NIT + 1
      IF (ABS(XN) .GT. 1.0D3) GO TO 30
      IF (ABS(XN - XFIX) .LE. TOL) GO TO 20
      XFIX = XN
      GO TO 10
   20 XFIX = XN
      RETURN
   30 XFIX = XN
      RETURN 1
      END
C
      INTEGER FUNCTION ISTEPS(A, B, H)
      DOUBLE PRECISION A, B, H
      ISTEPS = MAX0(INT((B - A + H) / H), 0)
      RETURN
      END
