C     NUMTHY - SMALL INTEGER SEQUENCE ROUTINES
C
C     COLLTZ  LENGTH AND PEAK OF THE 3N+1 TRAJECTORY STARTING AT N
C     IGCD    GREATEST COMMON DIVISOR BY EUCLID'S ALGORITHM
C     ILCM    LEAST COMMON MULTIPLE
C     GCDSEQ  GCD OF A VECTOR, STOPPING AS SOON AS IT REACHES ONE
C
C     ALL LOOPS ARE WRITTEN WITH NUMERIC LABELS, AS IN THE ORIGINAL
C     CARD DECK.  NO DO STATEMENTS ARE USED ANYWHERE IN THIS FILE.
C
      SUBROUTINE COLLTZ(N, MAXSTP, NSTEP, IPEAK, IERR)
C
C     FOLLOWS K -> K/2 (K EVEN) OR 3K+1 (K ODD) UNTIL K = 1.
C     NSTEP  NUMBER OF STEPS TAKEN
C     IPEAK  LARGEST VALUE REACHED (N ITSELF IF THE ORBIT NEVER RISES)
C     IERR   0  ORBIT REACHED 1
C            1  N IS NOT POSITIVE
C            2  MORE THAN MAXSTP STEPS WOULD BE NEEDED
C
      INTEGER N, MAXSTP, NSTEP, IPEAK, IERR
      NSTEP = 0
      IERR = 0
      IPEAK = N
      IF (N) 10, 10, 20
   10 IERR = 1
      RETURN
   20 K = N
   30 IF (K .EQ. 1) RETURN
      IF (NSTEP .GE. MAXSTP) GO TO 80
      IF (MOD(K, 2)) 40, 50, 40
   40 K = 3*K + 1
      GO TO 60
   50 K = K/2
   60 NSTEP = NSTEP + 1
      IF (K .GT. IPEAK) IPEAK = K
      GO TO 30
   80 IERR = 2
      RETURN
      END
C
      INTEGER FUNCTION IGCD(M, N)
C
C     EUCLID: REPLACE (A, B) BY (B, MOD(A, B)) UNTIL B IS ZERO.
C     THE SIGNS OF M AND N ARE IGNORED, IGCD(0, 0) = 0.
C
      INTEGER M, N
      IA = IABS(M)
      IB = IABS(N)
   10 IF (IB .EQ. 0) GO TO 20
      IR = MOD(IA, IB)
      IA = IB
      IB = IR
      GO TO 10
   20 IGCD = IA
      RETURN
      END
C
      INTEGER FUNCTION ILCM(M, N)
C     LEAST COMMON MULTIPLE, ALWAYS NON-NEGATIVE, 0 IF EITHER IS 0
      INTEGER M, N, IGCD
      IF (M .EQ. 0 .OR. N .EQ. 0) GO TO 10
      ILCM = IABS(M / IGCD(M, N) * N)
      RETURN
   10 ILCM = 0
      RETURN
      END
C
      SUBROUTINE GCDSEQ(N, A, G, NUSED)
C
C     G      GCD OF A(1) ... A(N); 0 WHEN N IS NOT POSITIVE
C     NUSED  HOW MANY ELEMENTS WERE LOOKED AT BEFORE THE RUNNING GCD
C            REACHED 1 (OR THE END OF THE VECTOR)
C
      INTEGER N, A(*), G, NUSED, I, IGCD
      G = 0
      NUSED = 0
      I = 1
   10 IF (I .GT. N) RETURN
      G = IGCD(G, A(I))
      NUSED = I
      IF (G .EQ. 1) RETURN
      I = I + 1
      GO TO 10
      END
