C     DECIMAL DIGIT UTILITIES AND RADIX CONVERSION.  ALL THE ARITHMETIC
C     IS INTEGER, SO EVERY DIVISION TRUNCATES TOWARD ZERO.
C
C     IDIGSM - SUM OF THE DECIMAL DIGITS OF |N|
      INTEGER FUNCTION IDIGSM(N)
      INTEGER N
      M = IABS(N)
      IDIGSM = 0
   10 IF (M .EQ. 0) GO TO 20
      IDIGSM = IDIGSM + MOD(M, 10)
      M = M/10
      GO TO 10
   20 RETURN
      END
C
C     IREV - REVERSE THE DECIMAL DIGITS OF N, KEEPING ITS SIGN
C     (IREV(120) IS 21 AND IREV(-120) IS -21)
      INTEGER FUNCTION IREV(N)
      INTEGER N
      M = IABS(N)
      IR = 0
   10 IF (M .EQ. 0) GO TO 20
      IR = IR*10 + MOD(M, 10)
      M = M/10
      GO TO 10
   20 IREV = ISIGN(IR, N)
      RETURN
      END
C
C     ISQRTI - FLOOR(SQRT(N)) FOR N >= 0 BY INTEGER NEWTON ITERATION
      INTEGER FUNCTION ISQRTI(N)
      INTEGER N
      ISQRTI = 0
      IF (N .LE. 0) RETURN
      IX = N
   10 IY = (IX + N/IX)/2
      IF (IY .GE. IX) GO TO 20
      IX = IY
      GO TO 10
   20 ISQRTI = IX
      RETURN
      END
C
C     ITOB - WRITE N IN BASE IBASE (2..16) INTO STR, LEFT JUSTIFIED
C     AND BLANK PADDED.  STR GETS '?' FOR AN UNSUPPORTED BASE AND
C     SIXTEEN '*' WHEN THE RESULT (WITH SIGN) DOES NOT FIT.
      SUBROUTINE ITOB(N, IBASE, STR)
      INTEGER N, IBASE
      CHARACTER*16 STR, DIGITS
      CHARACTER*40 BUF
      DATA DIGITS /'0123456789ABCDEF'/
      STR = ' '
      IF (IBASE .LT. 2 .OR. IBASE .GT. 16) THEN
         STR = '?'
         RETURN
      END IF
      M = IABS(N)
      NB = 0
   10 ID = MOD(M, IBASE)
      NB = NB + 1
      BUF(NB:NB) = DIGITS(ID+1:ID+1)
      M = M/IBASE
      IF (M .GT. 0) GO TO 10
      IF (N .LT. 0) THEN
         NB = NB + 1
         BUF(NB:NB) = '-'
      END IF
      IF (NB .GT. 16) THEN
         STR = '****************'
         RETURN
      END IF
C     BUF HOLDS THE LEAST SIGNIFICANT DIGIT FIRST: REVERSE IT
      DO 20 I = 1, NB
         STR(I:I) = BUF(NB+1-I:NB+1-I)
   20 CONTINUE
      RETURN
      END
C
C     ISTOI - PARSE STR (BASE IBASE 2..16, UPPER CASE DIGITS, OPTIONAL
C     LEADING MINUS, ENDED BY THE FIRST BLANK).  IERR = 0 IF ALL IS
C     WELL, THE POSITION OF THE OFFENDING CHARACTER OTHERWISE, AND -1
C     FOR AN UNSUPPORTED BASE.  THE VALUE IS 0 WHENEVER IERR .NE. 0.
      INTEGER FUNCTION ISTOI(STR, IBASE, IERR)
      CHARACTER*16 STR, DIGITS
      INTEGER IBASE, IERR
      DATA DIGITS /'0123456789ABCDEF'/
      ISTOI = 0
      IERR = 0
      IF (IBASE .LT. 2 .OR. IBASE .GT. 16) THEN
         IERR = -1
         RETURN
      END IF
      IS = 1
      IF (STR(1:1) .EQ. '-') IS = 2
      IV = 0
      DO 30 I = IS, 16
         IF (STR(I:I) .EQ. ' ') GO TO 40
         ID = INDEX(DIGITS(1:IBASE), STR(I:I))
         IF (ID .EQ. 0) THEN
            IERR = I
            ISTOI = 0
            RETURN
         END IF
         IV = IV*IBASE + (ID - 1)
   30 CONTINUE
   40 ISTOI = IV
      IF (IS .EQ. 2) ISTOI = -IV
      RETURN
      END
C
C     SHOWB - PRINT N AND ITS REPRESENTATION IN BASE IBASE
      SUBROUTINE SHOWB(N, IBASE)
      INTEGER N, IBASE
      CHARACTER*16 STR
      CALL ITOB(N, IBASE, STR)
      WRITE (6, 100) N, IBASE, STR
  100 FORMAT (1X, I10, ' IN BASE ', I2, ' IS ', A16)
      RETURN
      END
