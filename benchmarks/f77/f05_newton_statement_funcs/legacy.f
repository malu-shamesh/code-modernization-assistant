C     CBRTNW - REAL CUBE ROOT BY NEWTON ITERATION
C
C     SOLVES F(X) = X**3 - A = 0 WITH THE STATEMENT FUNCTIONS F AND
C     DF.  THE CONVERGENCE TOLERANCE IS A MULTIPLE OF THE MACHINE
C     RELATIVE SPACING, TAKEN FROM D1MACH(4) (PORT LIBRARY STYLE).
C
C     RELATIVE RESIDUAL TOLERANCE USED BY THE ITERATION
      DOUBLE PRECISION FUNCTION RELTOL()
      DOUBLE PRECISION D1MACH
      EXTERNAL D1MACH
      RELTOL = 10.0D0 * D1MACH(4)
      RETURN
      END
C
C     NEWTON ITERATION STARTING FROM X = A (OR 1 WHEN ABS(A) .LT. 1).
C     NMAX  MAXIMUM NUMBER OF RESIDUAL TESTS
C     ITER  NUMBER OF THE LAST TEST MADE; NMAX+1 AFTER A FAILURE
C     IERR  0 CONVERGED, 1 NOT CONVERGED WITHIN NMAX STEPS
      SUBROUTINE CBRTNW(A, X, NMAX, ITER, IERR)
      IMPLICIT DOUBLE PRECISION (A-H, O-Z)
      INTEGER NMAX, ITER, IERR
      DOUBLE PRECISION RELTOL
      F(Z) = Z*Z*Z - A
      DF(Z) = 3.0D0*Z*Z
      TOL = RELTOL() * DMAX1(1.0D0, DABS(A))
      IERR = 0
      X = A
      IF (DABS(A) .LT. 1.0D0) X = 1.0D0
      DO 10 ITER = 1, NMAX
         IF (DABS(F(X)) .LE. TOL) RETURN
         X = X - F(X) / DF(X)
   10 CONTINUE
      IERR = 1
      RETURN
      END
C
C     CUBE ROOT WITH A GENEROUS ITERATION LIMIT; THE LAST ITERATE IS
C     RETURNED EVEN WHEN THE ITERATION DID NOT CONVERGE
      DOUBLE PRECISION FUNCTION DCBRT(A)
      DOUBLE PRECISION A, X
      INTEGER ITER, IERR
      CALL CBRTNW(A, X, 60, ITER, IERR)
      DCBRT = X
      RETURN
      END
C
C     CUBE ROOTS OF A(1..N), RETURNING HOW MANY DID NOT CONVERGE
      INTEGER FUNCTION CBRTV(N, A, X)
      DOUBLE PRECISION A(*), X(*)
      INTEGER ITER, IERR, NBAD
      NBAD = 0
      DO 20 I = 1, N
         CALL CBRTNW(A(I), X(I), 60, ITER, IERR)
         IF (IERR .NE. 0) NBAD = NBAD + 1
   20 CONTINUE
      CBRTV = NBAD
      RETURN
      END
