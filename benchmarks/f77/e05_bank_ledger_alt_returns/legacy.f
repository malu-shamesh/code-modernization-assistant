C     CHECKING-ACCOUNT LEDGER
C
C     ONE ACCOUNT LIVES IN COMMON BLOCK /ACCT/:
C        BAL    CURRENT BALANCE
C        ODLIM  OVERDRAFT LIMIT (A WITHDRAWAL MAY NOT TAKE BAL BELOW
C               MINUS ODLIM)
C        NTX    TRANSACTIONS POSTED
C        NREJ   TRANSACTIONS REJECTED (INVALID OR DECLINED)
C
C     OPENAC  OPEN THE ACCOUNT
C     POSTTX  POST ONE TRANSACTION, ALTERNATE RETURNS ON REJECTION
C     RUNLED  POST A BATCH; STOPS AFTER THE SECOND DECLINED WITHDRAWAL
C     ACSTAT  REPORT BALANCE AND COUNTERS
C
      SUBROUTINE OPENAC(BAL0, LIMIT)
      DOUBLE PRECISION BAL0, LIMIT
      DOUBLE PRECISION BAL, ODLIM
      INTEGER NTX, NREJ
      COMMON /ACCT/ BAL, ODLIM, NTX, NREJ
      BAL = BAL0
      ODLIM = LIMIT
      NTX = 0
      NREJ = 0
      RETURN
      END
C
      SUBROUTINE POSTTX(ITYPE, AMT, NEWBAL, *, *)
C
C     ITYPE  1 DEPOSIT   2 WITHDRAWAL   3 FEE (NEVER REFUSED)
C            4 INTEREST, AMT IS A PERCENTAGE, PAID ONLY ON A POSITIVE
C              BALANCE
C     RETURN 1  UNKNOWN ITYPE OR NEGATIVE AMT, NOTHING POSTED
C     RETURN 2  WITHDRAWAL REFUSED BY THE OVERDRAFT LIMIT
C     NEWBAL ALWAYS RECEIVES THE BALANCE AFTER THE CALL.
C
      INTEGER ITYPE
      DOUBLE PRECISION AMT, NEWBAL
      DOUBLE PRECISION BAL, ODLIM
      INTEGER NTX, NREJ
      COMMON /ACCT/ BAL, ODLIM, NTX, NREJ
      IF (AMT .LT. 0.0D0) GO TO 900
      GO TO (100, 200, 300, 400), ITYPE
      GO TO 900
  100 BAL = BAL + AMT
      GO TO 800
  200 IF (BAL - AMT .LT. -ODLIM) GO TO 910
      BAL = BAL - AMT
      GO TO 800
  300 BAL = BAL - AMT
      GO TO 800
  400 IF (BAL) 800, 800, 410
  410 BAL = BAL + BAL * AMT / 100.0D0
  800 NTX = NTX + 1
      NEWBAL = BAL
      RETURN
  900 NREJ = NREJ + 1
      NEWBAL = BAL
      RETURN 1
  910 NREJ = NREJ + 1
      NEWBAL = BAL
      RETURN 2
      END
C
      SUBROUTINE RUNLED(N, KINDS, AMTS, NOK, NINV, NDEC, NDONE, FINAL)
C
C     POSTS TRANSACTION I = 1 .. N IN ORDER.  NOK, NINV AND NDEC COUNT
C     THE POSTED, INVALID AND DECLINED ONES; NDONE IS HOW MANY WERE
C     EXAMINED.  THE BATCH IS ABANDONED AS SOON AS TWO WITHDRAWALS
C     HAVE BEEN DECLINED.
C
      INTEGER N, KINDS(N), NOK, NINV, NDEC, NDONE
      DOUBLE PRECISION AMTS(N), FINAL, T
      DOUBLE PRECISION BAL, ODLIM
      INTEGER NTX, NREJ
      COMMON /ACCT/ BAL, ODLIM, NTX, NREJ
      NOK = 0
      NINV = 0
      NDEC = 0
      NDONE = 0
   10 IF (NDONE .GE. N) GO TO 60
      IF (NDEC .GE. 2) GO TO 60
      NDONE = NDONE + 1
      CALL POSTTX(KINDS(NDONE), AMTS(NDONE), T, *30, *40)
      NOK = NOK + 1
      GO TO 10
   30 NINV = NINV + 1
      GO TO 10
   40 NDEC = NDEC + 1
      GO TO 10
   60 FINAL = BAL
      RETURN
      END
C
      SUBROUTINE ACSTAT(CURBAL, NPOST, NREJCT)
      DOUBLE PRECISION CURBAL
      INTEGER NPOST, NREJCT
      DOUBLE PRECISION BAL, ODLIM
      INTEGER NTX, NREJ
      COMMON /ACCT/ BAL, ODLIM, NTX, NREJ
      CURBAL = BAL
      NPOST = NTX
      NREJCT = NREJ
      RETURN
      END
