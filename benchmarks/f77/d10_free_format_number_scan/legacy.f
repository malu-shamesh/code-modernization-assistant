C     NUMSCN - FREE FORMAT NUMBER SCANNER FOR CHARACTER DATA
C
C     SCANNM  CONVERT THE NUMBER AT THE START OF TEXT (LEADING BLANKS
C             ALLOWED): [SIGN] DIGITS [. DIGITS] [E|D [SIGN] DIGITS].
C             VALUE IS THE NUMBER AND NUSED THE POSITION OF ITS LAST
C             CHARACTER.  A TRAILING E WITHOUT DIGITS IS NOT PART OF IT.
C             ALTERNATE RETURN 1: NO NUMBER AT THE START OF TEXT
C             ALTERNATE RETURN 2: DECIMAL SCALE FACTOR BEYOND 10**300
C             (VALUE IS THEN 0 AND NUSED STILL TELLS WHAT WAS READ).
C     SCANLS  SCAN A LIST OF NUMBERS SEPARATED BY BLANKS OR COMMAS
C             INTO VALS(1..MAXV).  IERR = 0 OK, 1 SYNTAX ERROR,
C             2 RANGE ERROR, 3 MORE THAN MAXV VALUES.  IBAD IS THE
C             POSITION IN TEXT AT WHICH THE FAILING ITEM STARTS.
C
      SUBROUTINE SCANNM(TEXT, VALUE, NUSED, *, *)
      CHARACTER*(*) TEXT
      DOUBLE PRECISION VALUE
      INTEGER NUSED
      DOUBLE PRECISION MANT
      INTEGER I, N, K, ICLASS, LASTCL, NFRAC, NDIG, NEDIG
      INTEGER IEXP, ISIGN, JSIGN, IE, IFIRST
      LOGICAL SEENPT, INEXP
      CHARACTER*1 C
      VALUE = 0.0D0
      NUSED = 0
      N = LEN(TEXT)
C     SKIP LEADING BLANKS; I IS THE FIRST NON-BLANK ON LEAVING THE LOOP
      DO 5 I = 1, N
         IF (TEXT(I:I) .NE. ' ') GO TO 6
    5 CONTINUE
      RETURN 1
    6 IFIRST = I
      MANT = 0.0D0
      NFRAC = 0
      NDIG = 0
      NEDIG = 0
      IEXP = 0
      ISIGN = 1
      JSIGN = 1
      LASTCL = 0
      SEENPT = .FALSE.
      INEXP = .FALSE.
C     CHARACTER CLASSES: 1 DIGIT, 2 SIGN, 3 POINT, 4 E OR D, 5 OTHER
   10 IF (I .GT. N) GO TO 80
      C = TEXT(I:I)
      ICLASS = 5
      IF (C .GE. '0' .AND. C .LE. '9') ICLASS = 1
      IF (C .EQ. '+' .OR. C .EQ. '-') ICLASS = 2
      IF (C .EQ. '.') ICLASS = 3
      IF (INDEX('EDed', C) .GT. 0) ICLASS = 4
      GO TO (20, 30, 40, 50, 80), ICLASS
C     DIGIT
   20 K = ICHAR(C) - ICHAR('0')
      IF (INEXP) THEN
         IEXP = MIN(10 * IEXP + K, 9999)
         NEDIG = NEDIG + 1
      ELSE
         MANT = 10.0D0 * MANT + K
         NDIG = NDIG + 1
         IF (SEENPT) NFRAC = NFRAC + 1
      END IF
      GO TO 60
C     SIGN: ONLY AT THE VERY START, OR RIGHT AFTER THE EXPONENT LETTER
   30 IF (INEXP) THEN
         IF (LASTCL .NE. 4) GO TO 80
         IF (C .EQ. '-') JSIGN = -1
      ELSE
         IF (I .NE. IFIRST) GO TO 80
         IF (C .EQ. '-') ISIGN = -1
      END IF
      GO TO 60
C     DECIMAL POINT
   40 IF (INEXP .OR. SEENPT) GO TO 80
      SEENPT = .TRUE.
      GO TO 60
C     EXPONENT LETTER
   50 IF (INEXP .OR. NDIG .EQ. 0) GO TO 80
      INEXP = .TRUE.
C     REMEMBER THE LAST POSITION AT WHICH THE NUMBER IS COMPLETE
   60 IF (NDIG .GT. 0 .AND. (.NOT. INEXP .OR. NEDIG .GT. 0)) NUSED = I
      LASTCL = ICLASS
      I = I + 1
      GO TO 10
C     END OF THE NUMBER (NUSED IS 0 UNLESS A DIGIT WAS SEEN)
   80 IF (NDIG .EQ. 0) RETURN 1
      IE = JSIGN * IEXP - NFRAC
      IF (IABS(IE) .GT. 300) RETURN 2
      IF (IE .GE. 0) THEN
         VALUE = MANT * 10.0D0 ** IE
      ELSE
         VALUE = MANT / 10.0D0 ** (-IE)
      END IF
      VALUE = ISIGN * VALUE
      RETURN
      END
C
      SUBROUTINE SCANLS(TEXT, VALS, MAXV, NV, IERR, IBAD)
      CHARACTER*(*) TEXT
      INTEGER MAXV, NV, IERR, IBAD
      DOUBLE PRECISION VALS(MAXV)
      DOUBLE PRECISION V
      INTEGER I, IPOS, N, NU
      NV = 0
      IERR = 0
      IBAD = 0
      IPOS = 1
      N = LEN(TEXT)
C     SKIP SEPARATORS; NOTHING LEFT MEANS THE LIST IS COMPLETE
   10 DO 15 I = IPOS, N
         IF (TEXT(I:I) .NE. ' ' .AND. TEXT(I:I) .NE. ',') GO TO 20
   15 CONTINUE
      RETURN
   20 IF (NV .GE. MAXV) THEN
         IERR = 3
         IBAD = I
         RETURN
      END IF
      CALL SCANNM(TEXT(I:N), V, NU, *910, *920)
      NV = NV + 1
      VALS(NV) = V
      IPOS = I + NU
      GO TO 10
  910 IERR = 1
      IBAD = I
      RETURN
  920 IERR = 2
      IBAD = I
      RETURN
      END
