C     TAYLOR SERIES FOR EXP, SIN AND COS WITH CONVERGENCE TESTS, AND
C     A TABULATION ROUTINE.  EVERY ROUTINE REPORTS IN NTERMS HOW MANY
C     TERMS OF THE SERIES WERE ADDED.
C
C     TEXP - EXP(X) = SUM OF X**K/K!.  SUMMATION STOPS WHEN A TERM IS
C     SMALLER THAN TOL TIMES THE CURRENT SUM (RELATIVE TEST).
      DOUBLE PRECISION FUNCTION TEXP(X, TOL, NTERMS)
      DOUBLE PRECISION X, TOL, TERM, SUM
      INTEGER NTERMS, K
      TERM = 1.0D0
      SUM = 1.0D0
      NTERMS = 1
      DO 10 K = 1, 200
         TERM = TERM*X/DBLE(K)
         SUM = SUM + TERM
         NTERMS = NTERMS + 1
         IF (DABS(TERM) .LT. TOL*DABS(SUM)) GO TO 20
   10 CONTINUE
   20 TEXP = SUM
      RETURN
      END
C
C     TSIN - SIN(X) = X - X**3/3! + X**5/5! - ...  THE ARGUMENT IS
C     FIRST REDUCED MODULO 2*PI (DMOD KEEPS THE SIGN OF X).  ABSOLUTE
C     TEST: STOP WHEN A TERM IS SMALLER THAN EPS.
      DOUBLE PRECISION FUNCTION TSIN(X, EPS, NTERMS)
      DOUBLE PRECISION X, EPS, Y, TERM, SUM, TWOPI
      INTEGER NTERMS, K
      PARAMETER (TWOPI = 6.28318530717958648D0)
      Y = DMOD(X, TWOPI)
      TERM = Y
      SUM = Y
      NTERMS = 1
      DO 30 K = 1, 100
         TERM = -TERM*Y*Y/DBLE((2*K)*(2*K + 1))
         SUM = SUM + TERM
         NTERMS = NTERMS + 1
         IF (DABS(TERM) .LT. EPS) GO TO 40
   30 CONTINUE
   40 TSIN = SUM
      RETURN
      END
C
C     TCOS - COS(X) = SIN(X + PI/2), SO TSIN DOES THE WORK
      DOUBLE PRECISION FUNCTION TCOS(X, EPS, NTERMS)
      DOUBLE PRECISION X, EPS, TSIN, HALFPI
      INTEGER NTERMS
      DATA HALFPI /1.57079632679489662D0/
      TCOS = TSIN(X + HALFPI, EPS, NTERMS)
      RETURN
      END
C
C     EXPTAB - TAB(1..N) = EXP(X) FOR X = X0, X0+DX, ... WHILE THE
C     DO-LOOP TRIP COUNT (X1-X0+DX)/DX ALLOWS.  N RETURNS THE COUNT.
      SUBROUTINE EXPTAB(X0, X1, DX, TOL, TAB, N)
      DOUBLE PRECISION X0, X1, DX, TOL, TAB(*), X, TEXP
      INTEGER N, NT
      N = 0
      DO 50 X = X0, X1, DX
         N = N + 1
         TAB(N) = TEXP(X, TOL, NT)
   50 CONTINUE
      RETURN
      END
