C     CALENDAR ARITHMETIC AND SMALL NUMERIC UTILITIES WHOSE BEHAVIOUR
C     DEPENDS ON FORTRAN 77 SEMANTICS (TRUNCATING INTEGER DIVISION,
C     DO-LOOP TRIP COUNTS, COMPUTED GO TO, ARITHMETIC IF, COMMON).
C
C     CNTINI - INITIAL VALUES OF THE CALL AND STEP COUNTERS
      BLOCK DATA CNTINI
      COMMON /CNT/ NCALL, NSTEP
      DATA NCALL, NSTEP /0, 0/
      END
C
C     JDAY - JULIAN DAY NUMBER OF A GREGORIAN DATE (FLIEGEL AND VAN
C     FLANDERN).  THE FORMULA ONLY WORKS BECAUSE INTEGER DIVISION
C     TRUNCATES TOWARD ZERO: (IM-14)/12 IS -1 FOR JANUARY AND
C     FEBRUARY AND 0 FOR MARCH TO DECEMBER.
      INTEGER FUNCTION JDAY(IY, IM, ID)
      INTEGER IY, IM, ID, MA
      MA = (IM - 14)/12
      JDAY = ID - 32075 + 1461*(IY + 4800 + MA)/4
     &     + 367*(IM - 2 - MA*12)/12
     &     - 3*((IY + 4900 + MA)/100)/4
      RETURN
      END
C
C     CALDAT - INVERSE OF JDAY FOR JD > 0: THE GREGORIAN DATE
      SUBROUTINE CALDAT(JD, IY, IM, ID)
      INTEGER JD, IY, IM, ID
      L = JD + 68569
      N = 4*L/146097
      L = L - (146097*N + 3)/4
      I = 4000*(L + 1)/1461001
      L = L - 1461*I/4 + 31
      J = 80*L/2447
      K = L - 2447*J/80
      L = J/11
      J = J + 2 - 12*L
      I = 100*(N - 49) + I + L
      IY = I
      IM = J
      ID = K
      RETURN
      END
C
C     LASTI - RUN AN EMPTY-BODIED DO LOOP I = N, M, K (K .NE. 0) AND
C     RETURN THE VALUE OF I AFTER IT HAS FINISHED, TOGETHER WITH THE
C     NUMBER OF TRIPS: MAX(0, (M-N+K)/K) WITH TRUNCATING DIVISION.
      INTEGER FUNCTION LASTI(N, M, K, NTRIP)
      INTEGER N, M, K, NTRIP, I
      NTRIP = 0
      DO 10 I = N, M, K
         NTRIP = NTRIP + 1
   10 CONTINUE
      LASTI = I
      RETURN
      END
C
C     RNDMOD - ROUND X TO AN INTEGER BY MODE:
C        1 = NEAREST (HALVES AWAY FROM ZERO)   2 = TOWARD ZERO
C        3 = TOWARD MINUS INFINITY (FLOOR)     OTHER MODES GIVE 0
      INTEGER FUNCTION RNDMOD(X, MODE)
      REAL X
      INTEGER MODE, R
      GO TO (10, 20, 30), MODE
C     A COMPUTED GO TO WITH MODE OUT OF RANGE FALLS THROUGH TO HERE
      RNDMOD = 0
      RETURN
   10 RNDMOD = NINT(X)
      RETURN
   20 RNDMOD = INT(X)
      RETURN
   30 R = INT(X)
      IF (FLOAT(R) .GT. X) R = R - 1
      RNDMOD = R
      RETURN
      END
C
C     COLLTZ - NUMBER OF 3N+1 STEPS NEEDED TO REACH 1 (0 FOR N <= 1),
C     OR MINUS MAXIT IF MAXIT STEPS WERE NOT ENOUGH.  THE CALL AND
C     STEP TOTALS ARE ACCUMULATED IN COMMON /CNT/.
      INTEGER FUNCTION COLLTZ(N, MAXIT)
      INTEGER N, MAXIT, M, K
      COMMON /CNT/ NCALL, NSTEP
      NCALL = NCALL + 1
      M = N
      K = 0
   10 IF (M .LE. 1) GO TO 50
      IF (K .GE. MAXIT) GO TO 40
      IF (MOD(M, 2)) 20, 30, 20
   20 M = 3*M + 1
      GO TO 35
   30 M = M/2
   35 K = K + 1
      GO TO 10
   40 NSTEP = NSTEP + K
      COLLTZ = -K
      RETURN
   50 NSTEP = NSTEP + K
      COLLTZ = K
      RETURN
      END
C
C     CNTGET - CURRENT COUNTERS;  CNTRST - RESET THEM TO ZERO
      SUBROUTINE CNTGET(NC, NS)
      INTEGER NC, NS
      COMMON /CNT/ NCALL, NSTEP
      NC = NCALL
      NS = NSTEP
      RETURN
      END
C
      SUBROUTINE CNTRST
      COMMON /CNT/ NCALL, NSTEP
      NCALL = 0
      NSTEP = 0
      RETURN
      END
